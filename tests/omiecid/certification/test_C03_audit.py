def _index(payload) -> Dict[Tuple[str, int, Optional[str], str], List[Dict[str, Any]]]:
    idx: Dict[Tuple[str, int, Optional[str], str], List[Dict[str, Any]]] = {}
    for a in payload.get("assertions", []):
        if a.get("kind") != "oracle":
            continue
        m = _NAME_RE.match(a.get("name", ""))
        if not m:
            continue
        key = (m.group(1), int(m.group(2)), m.group(3), m.group(4))
        idx.setdefault(key, []).append(a)
    return idx


def _one(idx, problems: List[str], key) -> Optional[Dict[str, Any]]:
    got = idx.get(key, [])
    if len(got) != 1:
        problems.append(f"{key}: expected exactly one assertion, found {len(got)}")
        return None
    return got[0]


def _same_owner_count(payload) -> int:
    d = payload["draws"]
    return int(d["valid"]) - 2 * int(payload["seeds"]["count"])


def _ladder_seeds(payload) -> List[int]:
    s = payload["seeds"]
    return list(range(int(s["first"]), int(s["last"]) + 1))


