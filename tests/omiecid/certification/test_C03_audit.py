def _check_full_views(idx, p, construction, seed, variant, der, need_stamps=True, need_book=True):
    a = _one(idx, p, (construction, seed, variant, SUF_FILLED))
    if a is not None:
        obs = a["observed"]
        if not isinstance(obs, list) or len(obs) != len(set(map(str, obs))):
            p.append(f"{a['name']}: observed {obs!r} not a duplicate-free list")
        elif sorted(obs) != der["filled"]:
            p.append(f"{a['name']}: filled set {sorted(obs)} != derived {der['filled']}")
    a = _one(idx, p, (construction, seed, variant, SUF_SEQ))
    if a is not None and a["observed"] != der["seq"]:
        p.append(f"{a['name']}: sequence {a['observed']} != derived {der['seq']}")
    if need_book:
        a = _one(idx, p, (construction, seed, variant, SUF_BOOK))
        if a is not None:
            obs = a["observed"]
            view = {s: sorted(map(list, obs.get(s, []))) for s in ("BUY", "SELL")} \
                if isinstance(obs, dict) else None
            if view != der["book"]:
                p.append(f"{a['name']}: book {obs} != derived {der['book']}")
    if need_stamps:
        a = _one(idx, p, (construction, seed, variant, SUF_STAMPS))
        if a is not None:
            obs = a["observed"]
            try:
                oids = [int(e[0]) for e in obs]
                stamps = [e[1] for e in obs]
            except (TypeError, IndexError, ValueError):
                p.append(f"{a['name']}: unreadable stamps {obs!r}")
                return
            if oids != der["entry_order"]:
                p.append(f"{a['name']}: entry order {oids} != derived {der['entry_order']}")
            if any(len(s) != 1 for s in stamps):
                p.append(f"{a['name']}: an order holds != 1 stamp: {stamps}")
            else:
                flat = [tuple(s[0]) for s in stamps]
                if len(set(flat)) != len(flat):
                    p.append(f"{a['name']}: stamps not unique: {flat}")
                if any(not (x < y) for x, y in zip(flat, flat[1:])):
                    p.append(f"{a['name']}: stamps not strictly increasing in entry order: {flat}")


def _battery_ok(idx, p, construction, seed, variant):
    a = _one(idx, p, (construction, seed, variant, SUF_BATTERY))
    if a is None:
        return
    obs = a["observed"]
    if not isinstance(obs, dict) or set(obs) != set(CHECK_IDS):
        p.append(f"{a['name']}: battery keys {sorted(obs) if isinstance(obs, dict) else obs!r}")
        return
    for cid in CHECK_IDS:
        if obs[cid] != "pass":
            p.append(f"{a['name']}: {cid} = {obs[cid]!r}")
    if a["status"] != "pass":
        p.append(f"{a['name']}: status {a['status']!r}")


def _relation_ok(idx, p, key, evidence_want: Mapping[str, Any]):
    a = _one(idx, p, key)
    if a is None:
        return
    obs = a["observed"]
    if not isinstance(obs, dict) or obs.get("status") != "pass" or obs.get("violations"):
        p.append(f"{a['name']}: relation observed {obs!r}")
        return
    for k, v in evidence_want.items():
        if obs.get("evidence", {}).get(k) != v:
            p.append(f"{a['name']}: evidence {k} = {obs.get('evidence', {}).get(k)!r} != derived {v!r}")
    if a["status"] != "pass":
        p.append(f"{a['name']}: status {a['status']!r}")


def _observed_total(idx, construction, seed, variant) -> Optional[int]:
    got = idx.get((construction, seed, variant, SUF_SEQ), [])
    if len(got) != 1 or not isinstance(got[0]["observed"], list):
        return None
    try:
        return sum(int(e[3]) for e in got[0]["observed"])
    except (TypeError, IndexError, ValueError):
        return None


def check_ladders(payload, constructions=(LADDER, POT)) -> List[str]:
    """Per draw: the base run, the M1 reversal, the same-owner relabel and the
    edge variants of both ladder constructions, against the audit's own walk."""
    idx = _index(payload)
    p: List[str] = []
    seeds = _ladder_seeds(payload)
    n_same = _same_owner_count(payload)
    for c in constructions:
        variant_seeds = sorted({k[1] for k in idx if k[0] == c and k[2] in QTY_VARIANTS})
        self_seeds = sorted({k[1] for k in idx if k[0] == c and k[2] == "self_match"})
        if not variant_seeds:
            p.append(f"{c}: no edge-variant runs (one_tick_*, all_touch, into_decoys, shared_ts)")
        if not self_seeds:
            p.append(f"{c}: no self_match runs")
        for seed in seeds:
            sh = _shape(c, seed)
            base = derive(c, seed)
            # The card's own known result, restated from the walk: j earliest touch oids.
            j = base["n_fills"]
            if base["filled"] != sorted(sh["touch"][:j]) or any(d in base["filled"] for d in sh["decoys"]):
                p.append(f"{c} seed {seed}: audit walk disagrees with 'j earliest touch, decoys untouched'")
            if not 1 <= j < sh["k"]:
                p.append(f"{c} seed {seed}: j = {j} not in [1, k-1] (k = {sh['k']})")
            _check_full_views(idx, p, c, seed, None, base)
            # M1: entry-order reversal of the touch level.
            rev = derive(c, seed, "m1_reversal")
            if rev["filled"] != sorted(sh["touch"][::-1][:j]):
                p.append(f"{c} seed {seed}: reversal walk does not move the filled set")
            _battery_ok(idx, p, c, seed, "m1_reversal")
            _check_full_views(idx, p, c, seed, "m1_reversal", rev)
            _relation_ok(idx, p, (c, seed, "m1_reversal", SUF_M1),
                         {"base_volume": base["total"], "permuted_volume": rev["total"]})
        for seed in self_seeds:
            base = derive(c, seed)
            _battery_ok(idx, p, c, seed, "self_match")
            _check_full_views(idx, p, c, seed, "self_match", base, need_stamps=False, need_book=False)
            _relation_ok(idx, p, (c, seed, "self_match", SUF_M6), {"n_fills": base["n_fills"]})
        for seed in variant_seeds:
            sh = _shape(c, seed)
            for v in QTY_VARIANTS:
                total = _observed_total(idx, c, seed, v) if v == "into_decoys" else None
                if v == "into_decoys" and (total is None or total <= sh["k"] * sh["q_each"]):
                    p.append(f"{c} seed {seed} into_decoys: total {total} does not go past the touch "
                             f"level ({sh['k']} x {sh['q_each']})")
                    continue
                der = derive(c, seed, v, observed_total=total)
                _battery_ok(idx, p, c, seed, v)
                _check_full_views(idx, p, c, seed, v, der)
        # Shared-second runs (r2): fills / sequence / book against the walk with the
        # touch level (shared_ts) or the whole run (same_second) in ONE tape second.
        # Their stamp records are judged in check_shared_second_stamps, not here.
        for v, rel_suf in (("shared_ts", SUF_M1_TIE), ("same_second", SUF_M1_SS)):
            v_seeds = sorted({k[1] for k in idx if k[0] == c and k[2] == v})
            if not v_seeds:
                p.append(f"{c}: no {v} runs")
            for seed in v_seeds:
                sh = _shape(c, seed)
                der = derive(c, seed, v)
                rev = derive(c, seed, v + "_reversed")
                j = der["n_fills"]
                if der["filled"] != sorted(sh["touch"][:j]) or \
                        rev["filled"] != sorted(sh["touch"][::-1][:j]):
                    p.append(f"{c} seed {seed} {v}: walk is not 'j earliest-processed touch orders'")
                for vv, d in ((v, der), (v + "_reversed", rev)):
                    _battery_ok(idx, p, c, seed, vv)
                    _check_full_views(idx, p, c, seed, vv, d, need_stamps=False)
                _relation_ok(idx, p, (c, seed, v + "_reversed", rel_suf),
                             {"base_volume": der["total"], "permuted_volume": rev["total"]})
    # Every same-owner draw also exists; checked in check_same_owner.
    del n_same
    return p


def _stamp_list(entries) -> Optional[List[Tuple[int, Tuple[int, int]]]]:
    """``[[oid, [[sec, nsec]]], ...]`` -> ``[(oid, (sec, nsec)), ...]``; None if malformed
    (an order holding != 1 stamp counts as malformed)."""
    try:
        out = []
        for e in entries:
            oid, stamps = int(e[0]), e[1]
            if len(stamps) != 1:
                return None
            out.append((oid, (int(stamps[0][0]), int(stamps[0][1]))))
        return out
    except (TypeError, IndexError, ValueError):
        return None


def _queue_problems(pairs) -> List[str]:
    """§5.2 single global queue: unique and strictly increasing in entry order."""
    flat = [s for _, s in pairs]
    p = []
    if len(set(flat)) != len(flat):
        p.append(f"stamps not unique: {pairs}")
    if any(not (x < y) for x, y in zip(flat, flat[1:])):
        p.append(f"stamps not strictly increasing in entry order: {pairs}")
    return p


def _derived_groups(der, across: bool) -> List[List[int]]:
    """Resting orders sharing a tape second, in entry order. ``across=False``: groups of
    one (price, second) with >= 2 members; ``across=True``: groups of one second with
    >= 2 members that span more than one price."""
    groups: Dict[Any, List[int]] = {}
    for oid in der["entry_order"]:
        key = der["ts_of"][oid] if across else (der["price_of"][oid], der["ts_of"][oid])
        groups.setdefault(key, []).append(oid)
    out = []
    for g in groups.values():
        if len(g) < 2:
            continue
        if across and len({der["price_of"][o] for o in g}) < 2:
            continue
        out.append(g)
    return out


def shared_second_findings(payload, variants=SHARED_VARIANTS,
                           kinds=("global", "same", "across")) -> Dict[str, List[str]]:
    """Stamp records of the runs that share a tape second, against §5.2 / §13.1 as the
    audit reads them. Returns ``{assertion name: [problems]}`` for every flagged record
    (missing records are keyed by a synthetic name). ``kinds``:

    * ``global`` -- SUF_STAMPS: every resting order of the run, one stamp each, unique
      and strictly increasing in entry order (one global queue, whatever the price).
    * ``same``   -- SUF_SS_SAME: per (price, second) group, the same, restricted.
    * ``across`` -- SUF_SS_ACROSS: per second whose orders span >1 price, the same.
    """
    idx = _index(payload)
    out: Dict[str, List[str]] = {}
    for c in (LADDER, POT):
        for v in variants:
            seeds = sorted({k[1] for k in idx if k[0] == c and k[2] == v})
            if not seeds:
                out[f"{c} {v}: no runs"] = ["absent"]
            for seed in seeds:
                der = derive(c, seed, v)
                specs = []
                if "global" in kinds:
                    specs.append((SUF_STAMPS, None))
                if "same" in kinds:
                    specs.append((SUF_SS_SAME, _derived_groups(der, across=False)))
                if "across" in kinds:
                    specs.append((SUF_SS_ACROSS, _derived_groups(der, across=True)))
                for suf, want_groups in specs:
                    key = (c, seed, v, suf)
                    got = idx.get(key, [])
                    name = f"{c} seed {seed} {v}: {suf}"
                    if suf != SUF_STAMPS and not want_groups:
                        if got:
                            out[name] = [f"recorded, but the run has no such group"]
                        continue
                    if len(got) != 1:
                        out[name] = [f"expected exactly one assertion, found {len(got)}"]
                        continue
                    obs = got[0]["observed"]
                    probs: List[str] = []
                    if suf == SUF_STAMPS:
                        pairs = _stamp_list(obs) if isinstance(obs, list) else None
                        if pairs is None:
                            probs.append(f"unreadable stamps {obs!r}")
                        else:
                            if [o for o, _ in pairs] != der["entry_order"]:
                                probs.append(f"entry order {[o for o, _ in pairs]} != derived "
                                             f"{der['entry_order']}")
                            probs += _queue_problems(pairs)
                    else:
                        groups = [_stamp_list(g) for g in obs] if isinstance(obs, list) else None
                        if groups is None or any(g is None for g in groups):
                            probs.append(f"unreadable groups {obs!r}")
                        else:
                            if [[o for o, _ in g] for g in groups] != want_groups:
                                probs.append(f"groups {[[o for o, _ in g] for g in groups]} != "
                                             f"derived {want_groups}")
                            for g in groups:
                                probs += _queue_problems(g)
                    if probs:
                        out[name] = probs
    return out


def check_shared_second_stamps(payload, variants=SHARED_VARIANTS,
                               kinds=("global", "same", "across")) -> List[str]:
    return [f"{n}: {x}" for n, xs in shared_second_findings(payload, variants, kinds).items()
            for x in xs]


def check_same_owner(payload) -> List[str]:
    """§6.6 / M6 on the separate same-owner pair: the pair trades, exactly as the
    distinct-owner counterfactual, at the maker price for min(q_rest, q_agg)."""
    idx = _index(payload)
    p: List[str] = []
    n = _same_owner_count(payload)
    seen = sorted({k[1] for k in idx if k[0] == SAME})
    if seen != list(range(n)):
        p.append(f"{SAME}: seeds {seen[:5]}..{seen[-5:] if seen else []} != range({n})")
    for seed in range(n):
        d = _draw(SAME, seed)
        rows = _rows_of(d.tape)
        cf_rows = _rows_of(d.aux_tapes["counterfactual"])
        if len(rows) != 2 or len({r["agent"] for r in rows}) != 1:
            p.append(f"{SAME} seed {seed}: tape is not a same-owner pair")
            continue
        if len({r["agent"] for r in cf_rows}) != 2 or \
                [{**r, "agent": 0} for r in rows] != [{**r, "agent": 0} for r in cf_rows]:
            p.append(f"{SAME} seed {seed}: counterfactual is not the owner-relabelled pair")
        der = derive(SAME, seed)
        rest, agg = rows
        crosses = rest["price"] <= agg["price"] if agg["side"] == BUY else rest["price"] >= agg["price"]
        if not crosses or der["n_fills"] != 1 or der["seq"][0][3] != min(rest["qty"], agg["qty"]) \
                or der["seq"][0][2] != rest["price"]:
            p.append(f"{SAME} seed {seed}: audit walk does not give one maker-priced trade")
        _check_full_views(idx, p, SAME, seed, None, der)
        _battery_ok(idx, p, SAME, seed, "counterfactual")
        a = _one(idx, p, (SAME, seed, None, SUF_TRADES_CF))
        if a is not None:
            obs, cf = a["observed"], a["expected"]
            if not isinstance(obs, list) or len(obs) != 1:
                p.append(f"{a['name']}: same-owner trade list {obs!r} is not one trade (§6.6: must trade)")
            else:
                head = [int(x) for x in obs[0][:4]]
                want = [rest["price"], min(rest["qty"], agg["qty"]), rest["oid"], agg["oid"]]
                if head != want:
                    p.append(f"{a['name']}: trade {head} != derived {want}")
                if obs != cf:
                    p.append(f"{a['name']}: same-owner trade list {obs} != counterfactual {cf}")
        _relation_ok(idx, p, (SAME, seed, None, SUF_M6_SAME), {"n_fills": 1})
    return p


def check_eager_jit(payload) -> List[str]:
    """Eager-vs-jitted evidence must be PRESENT (absence is failure) and identical, for
    every construction's base run and every derived run kind it emits."""
    p: List[str] = []
    if payload.get("eager_jit_identical") is not True:
        p.append(f"eager_jit_identical = {payload.get('eager_jit_identical')!r}")
    ej = [a for a in payload["assertions"] if a["kind"] == "eager_jit"]
    if not ej:
        p.append("no eager_jit evidence in the payload")
        return p
    covered = set()
    for a in ej:
        if a["status"] != "pass" or a["observed"] is not True or a["expected"] is not True:
            p.append(f"{a['name']} ({a['detail']}): eager and jitted disagree")
        m = _EJ_DETAIL_RE.match(a.get("detail", ""))
        if not m:
            p.append(f"eager_jit detail unreadable: {a.get('detail')!r}")
            continue
        if a["name"] != f"eager == jitted (seed {m.group(2)})" or a["seed"] != int(m.group(2)):
            p.append(f"eager_jit name/seed {a['name']!r}/{a['seed']} disagree with detail {a['detail']!r}")
        covered.add((m.group(1), m.group(3)))
    idx = _index(payload)
    run_kinds = {(k[0], k[2]) for k in idx}
    for c in CONSTRUCTIONS:
        if (c, None) not in covered:
            p.append(f"eager_jit evidence missing for the base run of {c}")
    for kind in sorted(run_kinds, key=str):
        if kind not in covered:
            p.append(f"eager_jit evidence missing for run kind {kind}")
    return p


def check_battery(payload) -> List[str]:
    p: List[str] = []
    rows = {r["check_id"]: r for r in payload["invariants"]}
    valid = int(payload["draws"]["valid"])
    for cid in CHECK_IDS:
        r = rows.get(cid)
        if r is None:
            p.append(f"invariant {cid} absent from the battery")
            continue
        if r["status"] != "pass" or r["n_fail"] != 0 or r["failing_seeds"]:
            p.append(f"invariant {cid}: {r['status']} n_fail={r['n_fail']} seeds={r['failing_seeds']}")
        if r["n_pass"] + r["n_not_applicable"] != valid:
            p.append(f"invariant {cid}: n_pass + n_na = {r['n_pass'] + r['n_not_applicable']} != valid {valid}")
        # Every C03 draw implies a trade and a priority question: I4 and I9 must run.
        if cid in ("I4", "I8", "I9") and r["n_pass"] != valid:
            p.append(f"invariant {cid}: n_pass {r['n_pass']} != valid {valid} (must not be vacuous)")
    idx = _index(payload)
    if not any(k[3] in (SUF_M1, SUF_M1_TIE) for k in idx):
        p.append("M1 never evaluated")
    if not any(k[3] == SUF_M6_SAME for k in idx):
        p.append("M6 (same-owner pair) never evaluated")
    return p


def check_capacity(payload) -> List[str]:
    p: List[str] = []
    cap = payload["capacity"]
    if cap["envelope"] != CARD_ENVELOPE:
        p.append(f"capacity envelope {cap['envelope']} != card {CARD_ENVELOPE}")
    for axis, v in cap["peaks"].items():
        if v is not None and v > CARD_ENVELOPE[axis]:
            p.append(f"capacity peak {axis} = {v} > {CARD_ENVELOPE[axis]}")
    want_rest, want_trades = 0, 0
    for c, n in ((LADDER, CARD_DEFAULT_DRAWS), (POT, CARD_DEFAULT_DRAWS), (SAME, _same_owner_count(payload))):
        for seed in range(n):
            d = _draw(c, seed)
            for axis, lim in CARD_ENVELOPE.items():
                if int(d.capacity_bounds[axis]) > lim:
                    p.append(f"{c} seed {seed}: generator bound {axis} {d.capacity_bounds[axis]} > {lim}")
            der = derive(c, seed)
            want_rest = max(want_rest, len(_rows_of(d.tape)) - 1)
            want_trades = max(want_trades, der["n_fills"])
    if cap["peaks"].get("resting_per_side") is None or cap["peaks"]["resting_per_side"] < want_rest:
        p.append(f"peak resting_per_side {cap['peaks'].get('resting_per_side')} < derived {want_rest}")
    if cap["peaks"].get("trades") is None or cap["peaks"]["trades"] < want_trades:
        p.append(f"peak trades {cap['peaks'].get('trades')} < derived {want_trades}")
    if payload["draws"]["discarded"] != 0 and payload["draws"]["discard_rate"] == 0:
        p.append("discards without a discard rate")
    return p


def check_units(payload) -> List[str]:
    """Pass/fail is in integer ticks; no euro-denominated assertion exists."""
    p = []
    for a in payload["assertions"]:
        if a["unit"] not in ("price_int", "qty_int", "count", "bool", "other"):
            p.append(f"{a['name']}: unit {a['unit']!r}")
        for v in (a["expected"], a["observed"]):
            if isinstance(v, float):
                p.append(f"{a['name']}: float-valued comparison {v!r}")
    return p


ALL_CHECKS = (check_schema, check_header, check_status_consistency, check_generator, check_quotes,
              check_ladders, check_same_owner, check_eager_jit, check_battery,
              check_capacity, check_units, check_shared_second_stamps)


