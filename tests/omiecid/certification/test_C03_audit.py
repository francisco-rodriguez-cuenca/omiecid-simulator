def _first_seed(payload, construction, variant) -> int:
    return min(k[1] for k in _index(payload) if k[0] == construction and k[2] == variant)


def _cross_price_pair(construction, seed, variant) -> Tuple[int, int]:
    """Two resting orders of one derived cross-price same-second group, at DIFFERENT
    prices, in entry order (first, later)."""
    der = derive(construction, seed, variant)
    for g in _derived_groups(der, across=True):
        for i, a in enumerate(g):
            for b in g[i + 1:]:
                if der["price_of"][a] != der["price_of"][b]:
                    return a, b
    raise LookupError((construction, seed, variant))


def _set_stamp(entries, oid, stamp) -> None:
    hits = [e for e in entries if int(e[0]) == oid]
    assert len(hits) == 1, (oid, entries)
    hits[0][1] = copy.deepcopy(stamp)


def _stamp_of(entries, oid):
    return copy.deepcopy(next(e[1] for e in entries if int(e[0]) == oid))


def test_conforming_same_second_record_is_accepted(payload, tmp_path):
    """Non-null check of the cross-price detector, independent of the payload's own
    correctness (r3):

    1. the real payload yields NO global / across-price finding on either same-second
       variant (the r3 claim, E1);
    2. a copy in which ONE seed's later cross-price order is given the stamp of an
       earlier order at a different price in the same second (the r2 defect, planted
       consistently in the global record and the across-prices group, statuses left
       ``pass`` -- a self-agreeing notebook) is flagged on exactly those two records
       of that seed, for non-uniqueness, and nowhere else;
    3. re-sequencing that seed's records into one global queue (what §5.2 requires)
       is accepted again: a conforming record passes.
    """
    variants = ("same_second",)
    kinds = ("global", "across")
    # 1. Real payload: clean.
    real = shared_second_findings(payload, variants=SS_VARIANTS, kinds=kinds)
    assert real == {}, real

    # 2. Plant a cross-price duplicate on one seed.
    seed = _first_seed(payload, LADDER, "same_second")
    first, later = _cross_price_pair(LADDER, seed, "same_second")
    broken = copy.deepcopy(payload)
    a_glob = _find(broken, LADDER, seed, "same_second", SUF_STAMPS)
    a_acr = _find(broken, LADDER, seed, "same_second", SUF_SS_ACROSS)
    dup = _stamp_of(a_glob["observed"], first)
    _set_stamp(a_glob["observed"], later, dup)
    grp = [g for g in a_acr["observed"] if any(int(e[0]) == later for e in g)]
    assert len(grp) == 1 and any(int(e[0]) == first for e in grp[0]), a_acr["observed"]
    _set_stamp(grp[0], later, dup)
    for a in (a_glob, a_acr):
        a["expected"] = copy.deepcopy(a["observed"])
        a["status"] = "pass"
    broken = _reload(tmp_path, "C03_cross_price_dup.json", broken)
    found = shared_second_findings(broken, variants=variants, kinds=kinds)
    want = {f"{LADDER} seed {seed} same_second: {SUF_STAMPS}",
            f"{LADDER} seed {seed} same_second: {SUF_SS_ACROSS}"}
    assert set(found) == want, sorted(found)
    for n in want:
        assert any("not unique" in x for x in found[n]), found[n]
    assert check_status_consistency(broken) == []  # only the derivation catches the lie

    # 3. Re-sequence the planted seed into one global queue: accepted again.
    fixed = copy.deepcopy(broken)
    for suf in (SUF_STAMPS, SUF_SS_ACROSS):
        a = _find(fixed, LADDER, seed, "same_second", suf)
        groups = a["observed"] if suf == SUF_SS_ACROSS else [a["observed"]]
        for g in groups:
            sec = g[0][1][0][0]
            for i, e in enumerate(g):
                e[1] = [[sec, i]]
        a["expected"] = copy.deepcopy(a["observed"])
    fixed = _reload(tmp_path, "C03_global_queue.json", fixed)
    refound = shared_second_findings(fixed, variants=variants, kinds=kinds)
    assert refound == {}, refound


