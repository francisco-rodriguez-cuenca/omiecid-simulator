def _find(payload, construction, seed, variant, suffix) -> Dict[str, Any]:
    tag = f"{construction} seed {seed}{' ' + variant if variant else ''}: {suffix}"
    for a in payload["assertions"]:
        if a["name"] == tag:
            return a
    raise KeyError(tag)


def _lie(a: Dict[str, Any], observed: Any) -> None:
    """Overwrite observed AND expected, status pass: a notebook that agrees with itself."""
    a["observed"] = copy.deepcopy(observed)
    a["expected"] = copy.deepcopy(observed)
    a["status"] = "pass"


def _seed_with(construction, pred) -> int:
    for s in range(CARD_DEFAULT_DRAWS):
        if pred(_shape(construction, s), derive(construction, s)):
            return s
    raise LookupError(construction)


