def _rank_key(rule: str, rest_side: int):
    def price_key(o):
        return o["price"] if rest_side == SELL else -o["price"]

    # The time key is the global-queue stamp: (tape second, entry index). Within one
    # tape second the queue order is the processing order (§5.2; OQ-32 convention).
    if rule == "price_time":
        return lambda o: (price_key(o), o["ts"], o["_entry"])
    if rule == "time_only":          # broken: ignores price
        return lambda o: (o["ts"], o["_entry"])
    if rule == "latest_first":       # broken: tie-break reversed
        return lambda o: (price_key(o), -o["ts"], -o["_entry"])
    raise ValueError(rule)


def _walk(rows: Sequence[Mapping[str, int]], rule: str = "price_time") -> Dict[str, Any]:
    """Submit ``rows`` in order (NON limit orders). Returns the fills, in walk order, as
    ``[passive, aggressor, maker_price, qty, submission]`` and the final book."""
    book: Dict[int, List[Dict[str, int]]] = {BUY: [], SELL: []}
    fills: List[List[int]] = []
    for sub, r in enumerate(rows):
        r = {**r, "_entry": sub}
        opp_side = SELL if r["side"] == BUY else BUY
        opp = book[opp_side]
        rem = r["qty"]

        def crosses(o, r=r):
            return o["price"] <= r["price"] if r["side"] == BUY else o["price"] >= r["price"]

        key = _rank_key(rule, opp_side)
        while rem > 0:
            cands = [o for o in opp if o["qty"] > 0 and crosses(o)]
            if not cands:
                break
            best = min(cands, key=key)
            q = min(rem, best["qty"])
            fills.append([best["oid"], r["oid"], best["price"], q, sub])
            best["qty"] -= q
            rem -= q
        book[opp_side] = [o for o in opp if o["qty"] > 0]
        if rem > 0:
            book[r["side"]].append({**r, "qty": rem})
    for side in (BUY, SELL):
        book[side] = [{k: v for k, v in o.items() if k != "_entry"} for o in book[side]]
    return {"fills": fills, "book": book, "n_sub": len(rows)}


def _book_view(book) -> Dict[str, List[List[int]]]:
    return {name: sorted([o["price"], o["qty"], o["oid"]] for o in book[s])
            for name, s in (("BUY", BUY), ("SELL", SELL))}


def _seq_view(walk) -> List[List[Any]]:
    last = walk["n_sub"] - 1
    return [[p, a, px, q, sub == last] for p, a, px, q, sub in walk["fills"]]


def _rows_of(tape) -> List[Dict[str, int]]:
    out = []
    for r in tape:
        if int(r[C_OID]) >= 1:
            out.append({"oid": int(r[C_OID]), "side": int(r[C_SIDE]), "price": int(r[C_PRICE]),
                        "qty": int(r[C_QTY]), "ts": int(r[C_TS]), "agent": int(r[C_AGENT]),
                        "exec": int(r[C_EXEC]), "contract": int(r[C_CONTRACT])})
    return out


@functools.lru_cache(maxsize=None)
def _draw(construction: str, seed: int):
    from omiecid_simulator.jaxomiecid import omie_tape_synth as synth
    if construction == LADDER:
        return synth.make_priority_ladder(seed)
    if construction == POT:
        return synth.make_priority_ladder(seed, variant="price_over_time")
    if construction == SAME:
        return synth.make_same_owner_pair(seed)
    raise KeyError(construction)


def _shape(construction: str, seed: int) -> Dict[str, Any]:
    """Read the draw's structure from its tape (touch level, decoys, aggressor), using
    ``params`` only for which oids the generator *meant* as touch / decoy orders, and
    cross-checking that against the tape."""
    d = _draw(construction, seed)
    rows = _rows_of(d.tape)
    agg = rows[-1]
    resting = rows[:-1]
    sides = {r["side"] for r in resting}
    assert len(sides) == 1 and agg["side"] not in sides, f"{construction} {seed}: sides"
    rest_side = sides.pop()
    best = (min if rest_side == SELL else max)(r["price"] for r in resting)
    touch = [r["oid"] for r in resting if r["price"] == best]
    decoys = [r["oid"] for r in resting if r["price"] != best]
    params = d.params
    gen_decoys = params.get("decoy_oids", params.get("early_decoy_oids"))
    assert touch == list(params["at_touch_oids"]), f"{construction} {seed}: touch oids"
    assert sorted(decoys) == sorted(gen_decoys), f"{construction} {seed}: decoy oids"
    q_each = {r["qty"] for r in resting}
    assert len(q_each) == 1, f"{construction} {seed}: unequal resting quantities"
    for r in rows:
        assert r["exec"] == 0, f"{construction} {seed}: not NON"  # ExecRestriction.NON
    assert len({r["ts"] for r in rows}) == len(rows), f"{construction} {seed}: tape ts not unique"
    assert [r["ts"] for r in rows] == sorted(r["ts"] for r in rows), f"{construction} {seed}: ts order"
    return {"rows": rows, "agg": agg, "rest_side": rest_side, "touch": touch, "decoys": decoys,
            "q_each": q_each.pop(), "p_touch": best, "k": len(touch)}


def _with_agg_qty(rows, qty: int):
    return [dict(r) for r in rows[:-1]] + [{**rows[-1], "qty": int(qty)}]


def _reversed_touch(sh) -> List[Dict[str, int]]:
    """M1: the touch orders enter in reverse order; every row keeps its slot's stamp."""
    rows = [dict(r) for r in sh["rows"]]
    slots = [i for i, r in enumerate(rows) if r["oid"] in sh["touch"]]
    touch_rows = [rows[i] for i in slots][::-1]
    for i, tr in zip(slots, touch_rows):
        rows[i] = {**tr, "ts": sh["rows"][i]["ts"]}
    return rows


def _derived_rows(construction: str, seed: int, variant: Optional[str],
                  observed_total: Optional[int] = None) -> List[Dict[str, int]]:
    if construction == SAME:
        if variant not in (None, "counterfactual"):
            raise KeyError(variant)
        return _rows_of(_draw(SAME, seed).tape)
    sh = _shape(construction, seed)
    rows = [dict(r) for r in sh["rows"]]
    q, k = sh["q_each"], sh["k"]
    base_q = sh["agg"]["qty"]
    if variant in (None, "self_match", "counterfactual"):
        return rows
    if variant == "m1_reversal":
        return _reversed_touch(sh)
    if variant in ("shared_ts", "shared_ts_reversed"):
        # The touch level shares ONE tape second (its first row's); decoys keep theirs.
        base = _reversed_touch(sh) if variant.endswith("_reversed") else rows
        t0 = min(r["ts"] for r in sh["rows"] if r["oid"] in sh["touch"])
        return [{**r, "ts": t0} if r["oid"] in sh["touch"] else r for r in base]
    if variant in ("same_second", "same_second_reversed"):
        # Every row of the run shares ONE tape second (the tape's first).
        base = _reversed_touch(sh) if variant.endswith("_reversed") else rows
        t0 = sh["rows"][0]["ts"]
        return [{**r, "ts": t0} for r in base]
    if variant == "one_tick_over":
        return _with_agg_qty(rows, base_q + 1)
    if variant == "one_tick_under":
        return _with_agg_qty(rows, base_q - 1)
    if variant == "all_touch":
        return _with_agg_qty(rows, k * q)
    if variant == "into_decoys":
        # Name-defined: the aggressor is sized beyond the whole touch level. The audit
        # takes its size from the run's total, but requires it to exceed k * q; which
        # orders fill and in what order are then fully determined by §6.1.
        assert observed_total is not None
        return _with_agg_qty(rows, observed_total)
    raise KeyError(variant)


def derive(construction: str, seed: int, variant: Optional[str] = None,
           observed_total: Optional[int] = None, rule: str = "price_time") -> Dict[str, Any]:
    rows = _derived_rows(construction, seed, variant, observed_total)
    w = _walk(rows, rule)
    agg_oid = rows[-1]["oid"]
    passive = [r for r in rows if r["oid"] != agg_oid]
    return {
        "filled": sorted({f[0] for f in w["fills"]}),
        "seq": _seq_view(w),
        "book": _book_view(w["book"]),
        "entry_order": [r["oid"] for r in passive],  # processing order = queue order
        "ts_of": {r["oid"]: r["ts"] for r in passive},
        "price_of": {r["oid"]: r["price"] for r in passive},
        "total": sum(f[3] for f in w["fills"]),
        "n_fills": len(w["fills"]),
        "fills_price_qty": sorted([f[2], f[3]] for f in w["fills"]),
        "agg_oid": agg_oid,
    }


