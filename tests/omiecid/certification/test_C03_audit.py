def check_header(payload) -> List[str]:
    p = []
    if payload.get("cert_id") != "C03":
        p.append(f"cert_id {payload.get('cert_id')!r}")
    if payload.get("notebook") != "C03_priority_ties_and_ownership.ipynb":
        p.append(f"notebook {payload.get('notebook')!r}")
    ok = payload.get("oracle_kind", "")
    for token in ("exact-parametric", "M1", "M6"):
        if token not in ok:
            p.append(f"oracle_kind {ok!r} lacks {token!r} (card: exact-parametric, plus M1 and M6)")
    d = payload["draws"]
    if d["requested"] != d["valid"] + d["discarded"]:
        p.append(f"draws: requested {d['requested']} != valid + discarded")
    s = payload["seeds"]
    if s["count"] != CARD_DEFAULT_DRAWS or s["first"] != 0 or s["last"] != CARD_DEFAULT_DRAWS - 1:
        p.append(f"seeds {s} do not cover the card's default 500 ladder draws")
    if _same_owner_count(payload) < 1:
        p.append("no same-owner (M6) draws: the card requires a separate M6 draw")
    if payload.get("environment", {}).get("backend") != "cpu":
        p.append(f"backend {payload.get('environment', {}).get('backend')!r}: device policy is CPU")
    return p


def check_status_consistency(payload) -> List[str]:
    """Every recorded comparison's status follows from its own expected/observed, and
    the top-level status follows from the assertions. A notebook that writes "pass"
    over a mismatch is caught here."""
    p = []
    comparable = (SUF_FILLED, SUF_SEQ, SUF_BOOK, SUF_TRADES_CF)
    any_fail = False
    for a in payload["assertions"]:
        if a["status"] == "fail":
            any_fail = True
        m = _NAME_RE.match(a["name"])
        if m and m.group(4) in comparable:
            same = a["expected"] == a["observed"]
            if (a["status"] == "pass") != same:
                p.append(f"{a['name']}: status {a['status']!r} but expected==observed is {same}")
    if any_fail and payload["status"] == "PASS":
        p.append("status PASS with a failing assertion")
    return p


