def _write_and_load(tmp_path: Path, p: Dict[str, Any], name: str) -> Dict[str, Any]:
    f = tmp_path / f"{name}.json"
    f.write_text(json.dumps(p), encoding="utf-8")
    return json.loads(f.read_text(encoding="utf-8"))


def _find(p, seed: int, suffix: str) -> dict:
    hits = [a for a in p["assertions"] if a.get("name") == f"seed {seed}: {suffix}"]
    assert len(hits) == 1
    return hits[0]


