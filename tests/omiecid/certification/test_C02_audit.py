REPO_ROOT = Path(__file__).resolve().parents[3]
DOCS = REPO_ROOT / "docs" / "omiecid"
DEFAULT_RESULTS_DIR = REPO_ROOT / "notebooks" / "certification" / "results"

CONSTRUCTION = "C02.crossing_pair"
CHECK_IDS = ("RB", "I1", "I2", "I3", "I4", "I5", "I6", "I7", "I8", "I9")
CARD_ENVELOPE = {"resting_per_side": 80, "trades": 80, "hops": 160, "concurrent_icebergs": 800}
CARD_DEFAULT_DRAWS = 500  # card: "Random scenarios default to 500 draws."

# Tape columns (generator module docstring; the loader's 13-wide layout).
C_CONTRACT, C_SIDE, C_PRICE, C_QTY, C_OID, C_AGENT, C_TS, C_EXEC = 0, 1, 2, 3, 4, 5, 6, 7

# Per-draw oracle assertions the card's pass criterion needs ("Per draw, exact
# integer equality on price and quantity"), plus count and identity.
SUF_COUNT = "number of trades"
SUF_PRICE = "trade price (resting order's limit)"
SUF_QTY = "trade quantity"
SUF_WHO = "who traded"
DRAW_SUFFIXES = (SUF_COUNT, SUF_PRICE, SUF_QTY, SUF_WHO)
_SEED_RE = re.compile(r"^seed (\d+): (.+)$")
_TWIN_RE = re.compile(r"^seed (\d+) twin ([a-z_]+): (.+)$")
_DETAIL_P = re.compile(r"^p_rest (-?\d+), p_agg (-?\d+)$")
_DETAIL_Q = re.compile(r"^q_rest (\d+), q_agg (\d+)$")
_EJ_RE = re.compile(r"^seed (\d+)(?: twin ([a-z_]+))?: identical$")

TWIN_KINDS = ("one_tick", "touch", "one_short", "equal_size", "wide_gap", "negative")

# The card's quoted passages (agile-plan C02 "Input artifacts"), plus §6.2 item 3, the
# rule the card says it certifies. Texts byte-copied from market-spec.md.
REQUIRED_QUOTES = (
    ("§6.1", "A match occurs when best bid price ≥ best ask price."),
    ("§11.1", "| Execution price = resting order's limit price in regular matching "
              "| Continuous Trading Matching Algorithm §5.1.1 |"),
    ("§6.2 item 3", "Trade executes at the **resting order's limit price** (maker pricing). "
                    "Source: Continuous Trading Matching Algorithm §5.1.1."),
)


