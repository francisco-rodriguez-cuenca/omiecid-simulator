def check_schema_and_kinds(payload) -> List[str]:
    from notebooks.certification.cert_support import derive_failure_kinds, validate_results
    errs = [f"schema: {e}" for e in validate_results(payload)]
    try:
        if payload.get("failure_kinds") != derive_failure_kinds(payload):
            errs.append("failure_kinds differ from those derived from the payload")
    except Exception as exc:  # noqa: BLE001
        errs.append(f"derive_failure_kinds raised {exc!r}")
    if payload.get("cert_id") != "C02":
        errs.append(f"cert_id {payload.get('cert_id')!r}")
    if payload.get("oracle_kind") != "exact-parametric":
        errs.append(f"oracle_kind {payload.get('oracle_kind')!r} (card: exact-parametric)")
    return errs


def check_draw_accounting(payload) -> List[str]:
    errs = []
    d, s = payload["draws"], payload["seeds"]
    if d["requested"] != CARD_DEFAULT_DRAWS:
        errs.append(f"draws.requested {d['requested']} != card default {CARD_DEFAULT_DRAWS}")
    if d["valid"] != d["requested"]:
        errs.append(f"accounting: valid {d['valid']} != requested {d['requested']} (INVALID draws are re-drawn)")
    seeds = sorted(_draw_assertions(payload))
    if len(seeds) != d["valid"] or s["count"] != d["valid"]:
        errs.append(f"accounting: {len(seeds)} seeds asserted, seeds.count {s['count']}, valid {d['valid']}")
    if seeds and (s["first"] != seeds[0] or s["last"] != seeds[-1]):
        errs.append(f"accounting: seeds.first/last {s['first']}/{s['last']} != asserted {seeds[0]}/{seeds[-1]}")
    if len(set(seeds)) != len(seeds):
        errs.append("accounting: duplicate seeds")
    return errs


def check_per_draw_oracle(payload) -> List[str]:
    """Card pass criterion: per draw, exact integer equality on price and quantity."""
    errs: List[str] = []
    by_seed = _draw_assertions(payload)
    if not by_seed:
        return ["oracle: no per-draw assertions"]
    for seed in sorted(by_seed):
        got = by_seed[seed]
        want = derive(seed)
        for suf in DRAW_SUFFIXES:
            n = len(got.get(suf, []))
            if n != 1:
                errs.append(f"seed {seed}: {n} '{suf}' assertions (want 1)")
        if any(len(got.get(suf, [])) != 1 for suf in DRAW_SUFFIXES):
            continue
        if want["n_trades"] != 1:
            errs.append(f"seed {seed}: generator tape does not cross (dataset precondition)")
            continue
        errs += _exact(got[SUF_COUNT][0], 1, f"seed {seed} count")
        pa = got[SUF_PRICE][0]
        if pa.get("unit") != "price_int":
            errs.append(f"seed {seed} price: unit {pa.get('unit')!r}, not integer ticks")
        if pa.get("observed") == want["p_agg"]:
            errs.append(f"seed {seed} price: TAKER-PRICED trade (observed p_agg {want['p_agg']}, "
                        f"resting limit is {want['p_rest']})")
        errs += _exact(pa, want["price"], f"seed {seed} price")
        m = _DETAIL_P.match(pa.get("detail", ""))
        if not m or (int(m.group(1)), int(m.group(2))) != (want["p_rest"], want["p_agg"]):
            errs.append(f"seed {seed} price: detail {pa.get('detail')!r} != regenerated tape "
                        f"p_rest {want['p_rest']}, p_agg {want['p_agg']}")
        qa = got[SUF_QTY][0]
        if qa.get("unit") != "qty_int":
            errs.append(f"seed {seed} qty: unit {qa.get('unit')!r}, not integer ticks")
        errs += _exact(qa, want["qty"], f"seed {seed} qty")
        m = _DETAIL_Q.match(qa.get("detail", ""))
        if not m or (int(m.group(1)), int(m.group(2))) != (want["q_rest"], want["q_agg"]):
            errs.append(f"seed {seed} qty: detail {qa.get('detail')!r} != regenerated tape "
                        f"q_rest {want['q_rest']}, q_agg {want['q_agg']}")
        errs += _exact(got[SUF_WHO][0], want["who"], f"seed {seed} who traded")
    return errs


def _twin_want(seed: int, kind: str, got: Mapping[str, List[dict]]) -> Optional[Dict[str, Any]]:
    """Expectation of one twin. Twins that keep the base prices are derived from the
    base draw alone; wide_gap / negative read their (p_rest, p_agg) from the twin's own
    detail and are held to the property that defines them."""
    b = derive(seed)
    agg_buy = b["agg_side"] == "BUY"
    sign = 1 if agg_buy else -1          # direction in which the aggressor crosses
    p_rest, q_rest, q_agg = b["p_rest"], b["q_rest"], b["q_agg"]
    if kind == "one_tick":
        p_agg = p_rest + sign
    elif kind == "touch":
        p_agg = p_rest
    elif kind == "one_short":
        p_agg = p_rest - sign
    elif kind == "equal_size":
        p_agg, q_agg = b["p_agg"], q_rest
    elif kind in ("wide_gap", "negative"):
        pa = got.get(SUF_PRICE, [{}])[0]
        m = _DETAIL_P.match(pa.get("detail", ""))
        if not m:
            return None
        p_rest, p_agg = int(m.group(1)), int(m.group(2))
    else:
        return None
    buyer, seller = (2, 1) if agg_buy else (1, 2)
    crosses = (p_agg >= p_rest) if agg_buy else (p_agg <= p_rest)
    return {"p_rest": p_rest, "p_agg": p_agg, "q_rest": q_rest, "q_agg": q_agg, "crosses": crosses,
            "gap": sign * (p_agg - p_rest), "base": b,
            "who": {"trades": [{"passive_oid": 1, "aggressor_oid": 2, "buyer_oid": buyer,
                                "seller_oid": seller, "on_aggressor_submission": True}] if crosses else [],
                    "accepted": [1, 2]}}


def check_twins(payload) -> List[str]:
    """The no-match boundary and the gap / size / sign edges."""
    errs: List[str] = []
    twins = _twin_assertions(payload)
    kinds = {k for (_, k) in twins}
    missing = set(TWIN_KINDS) - kinds
    if "one_short" in missing:
        errs.append("twins: no no-match boundary (one tick short) twin")
    if "touch" in missing:
        errs.append("twins: no touch (bid == ask crosses) twin")
    if "one_tick" in missing:
        errs.append("twins: no one-tick-gap twin")
    zero = _zero_eur_int()
    for (seed, kind), got in sorted(twins.items()):
        lab = f"seed {seed} twin {kind}"
        w = _twin_want(seed, kind, got)
        if w is None:
            errs.append(f"{lab}: cannot derive")
            continue
        bat = got.get("battery (RB, I1-I9) passes", [])
        if len(bat) != 1 or bat[0].get("status") != "pass":
            errs.append(f"{lab}: battery assertion missing or failing")
        if kind == "wide_gap":
            if not (w["p_rest"] == w["base"]["p_rest"] and w["gap"] > w["base"]["gap"]):
                errs.append(f"{lab}: not a wider gap at the base resting price")
        if kind == "negative":
            if not (w["p_rest"] < zero and w["gap"] == w["base"]["gap"]):
                errs.append(f"{lab}: resting price {w['p_rest']} not below 0 EUR ({zero}) at the base gap")
        if w["crosses"]:
            if kind == "one_short":
                errs.append(f"{lab}: derived as crossing")
            for suf in DRAW_SUFFIXES:
                if len(got.get(suf, [])) != 1:
                    errs.append(f"{lab}: {len(got.get(suf, []))} '{suf}' assertions")
            if any(len(got.get(suf, [])) != 1 for suf in DRAW_SUFFIXES):
                continue
            pa = got[SUF_PRICE][0]
            if pa.get("observed") == w["p_agg"] and w["p_agg"] != w["p_rest"]:
                errs.append(f"{lab}: TAKER-PRICED trade (observed p_agg {w['p_agg']})")
            errs += _exact(got[SUF_COUNT][0], 1, f"{lab} count")
            errs += _exact(pa, w["p_rest"], f"{lab} price")
            errs += _exact(got[SUF_QTY][0], min(w["q_rest"], w["q_agg"]), f"{lab} qty")
            m = _DETAIL_Q.match(got[SUF_QTY][0].get("detail", ""))
            if not m or (int(m.group(1)), int(m.group(2))) != (w["q_rest"], w["q_agg"]):
                errs.append(f"{lab} qty: detail {got[SUF_QTY][0].get('detail')!r} != "
                            f"q_rest {w['q_rest']}, q_agg {w['q_agg']}")
            errs += _exact(got[SUF_WHO][0], w["who"], f"{lab} who traded")
        else:
            if kind != "one_short":
                errs.append(f"{lab}: derived as non-crossing")
            for suf in (SUF_COUNT, SUF_QTY, "both orders rest unchanged"):
                if len(got.get(suf, [])) != 1:
                    errs.append(f"{lab}: {len(got.get(suf, []))} '{suf}' assertions")
            if SUF_PRICE in got or SUF_WHO in got:
                errs.append(f"{lab}: a no-match twin carries a trade-price / who-traded assertion")
            if any(len(got.get(suf, [])) != 1 for suf in (SUF_COUNT, SUF_QTY, "both orders rest unchanged")):
                continue
            errs += _exact(got[SUF_COUNT][0], 0, f"{lab} count")
            errs += _exact(got[SUF_QTY][0], 0, f"{lab} qty")
            b = w["base"]
            resting = {b["rest_side"]: [[w["p_rest"], w["q_rest"], 1]],
                       b["agg_side"]: [[w["p_agg"], w["q_agg"], 2]]}
            errs += _exact(got["both orders rest unchanged"][0], {"resting": resting, "accepted": [1, 2]},
                           f"{lab} resting")
    return errs


def check_eager_jit(payload) -> List[str]:
    """Card common criterion: the eager and jitted runs agree. Absence is a failure."""
    errs: List[str] = []
    ej = [a for a in payload.get("assertions", []) if a.get("kind") == "eager_jit"]
    if not ej:
        errs.append("eager_jit: NO eager-vs-jitted evidence in the payload")
    if payload.get("eager_jit_identical") is not True:
        errs.append(f"eager_jit: eager_jit_identical is {payload.get('eager_jit_identical')!r}, not true")
    draw_seeds = set(_draw_assertions(payload))
    covered_main = set()
    for a in ej:
        if a.get("status") != "pass" or a.get("expected") is not True or a.get("observed") is not True:
            errs.append(f"eager_jit: {a.get('name')!r} / {a.get('detail')!r} not identical")
        m = _EJ_RE.match(a.get("detail", ""))
        if not m or int(m.group(1)) != a.get("seed"):
            errs.append(f"eager_jit: unreadable detail {a.get('detail')!r}")
            continue
        if m.group(2) is None:
            covered_main.add(int(m.group(1)))
    if ej and not (covered_main & draw_seeds):
        errs.append("eager_jit: no main-dataset draw was run both eager and jitted")
    return errs


def check_battery(payload) -> List[str]:
    errs: List[str] = []
    rows = payload.get("invariants", [])
    ids = [r.get("check_id") for r in rows]
    if sorted(ids) != sorted(CHECK_IDS):
        errs.append(f"battery: check ids {ids} != full battery {list(CHECK_IDS)}")
    valid = payload["draws"]["valid"]
    for r in rows:
        cid = r.get("check_id")
        if r.get("status") != "pass" or r.get("n_fail") or r.get("failing_seeds"):
            errs.append(f"battery: {cid} status {r.get('status')!r}, n_fail {r.get('n_fail')}")
        if r.get("n_pass", 0) + r.get("n_fail", 0) + r.get("n_not_applicable", 0) != valid:
            errs.append(f"battery: {cid} counts do not cover the {valid} valid draws")
        if cid in ("I1", "I5", "I8", "I9") and r.get("n_pass") != valid:
            errs.append(f"battery: {cid} passed on {r.get('n_pass')} of {valid} draws (must apply to every draw)")
    return errs


def check_capacity(payload) -> List[str]:
    errs: List[str] = []
    cap = payload.get("capacity", {})
    if cap.get("envelope") != CARD_ENVELOPE:
        errs.append(f"capacity: envelope {cap.get('envelope')} != card {CARD_ENVELOPE}")
    peaks = cap.get("peaks", {})
    for k, lim in CARD_ENVELOPE.items():
        v = peaks.get(k)
        if v is not None and v > lim:
            errs.append(f"capacity: peak {k} {v} > {lim}")
    seeds = sorted(_draw_assertions(payload))
    ders = [derive(s) for s in seeds]
    if ders:
        if peaks.get("resting_per_side") != max(d["peak_resting_per_side"] for d in ders):
            errs.append(f"capacity: peak resting_per_side {peaks.get('resting_per_side')} != derived 1")
        if peaks.get("trades") != max(d["peak_trades"] for d in ders):
            errs.append(f"capacity: peak trades {peaks.get('trades')} != derived 1")
        hb = max(d["hops_bound"] for d in ders)
        if hb > CARD_ENVELOPE["hops"]:
            errs.append(f"capacity: generator hop bound {hb} > 160")
    if peaks.get("concurrent_icebergs") not in (0, None):
        errs.append(f"capacity: icebergs in a NON-only scenario ({peaks.get('concurrent_icebergs')})")
    if peaks.get("hops") is None:
        i8 = [r for r in payload.get("invariants", []) if r.get("check_id") == "I8"]
        if not i8 or "matching_iterations" not in i8[0].get("unobserved", []):
            errs.append("capacity: hops peak null but I8 does not report matching_iterations unobserved")
    return errs


def check_dataset_classes(payload) -> List[str]:
    seeds = sorted(_draw_assertions(payload))
    counts: Dict[str, int] = {}
    for s in seeds:
        c = derive(s)["cls"]
        counts[c] = counts.get(c, 0) + 1
    errs = []
    for need in ("BUY/q_agg<q_rest", "BUY/q_agg>q_rest", "SELL/q_agg<q_rest", "SELL/q_agg>q_rest"):
        if counts.get(need, 0) < 1:
            errs.append(f"dataset: class {need} never drawn")
    rows = [a for a in payload.get("assertions", []) if a.get("name", "").startswith("dataset: the four classes")]
    if len(rows) != 1 or rows[0].get("observed") != counts or rows[0].get("status") != "pass":
        errs.append(f"dataset: reported class counts {rows[0].get('observed') if rows else None} != derived {counts}")
    gaps = [derive(s)["gap"] for s in seeds]
    if gaps and min(gaps) < 1:
        errs.append(f"dataset: a draw with gap {min(gaps)} < 1 tick (card: Δ ≥ 1 tick)")
    return errs


def check_quotes(payload) -> List[str]:
    from notebooks.certification.cert_support import SpecQuote, check_quote, quote_digest
    errs: List[str] = []
    quotes = payload["spec"]["quotes"]
    if not quotes:
        errs.append("quotes: none")
    status = re.search(r"^\*\*Status:\*\*\s*(v[\d.]+)", (DOCS / "market-spec.md").read_text(encoding="utf-8"), re.M)
    for q in quotes:
        if not q.get("ok") or q.get("reason") != "ok":
            errs.append(f"quotes: {q.get('section')} {q.get('digest')} not ok ({q.get('reason')})")
        if q.get("source") == "market-spec.md" and status and q.get("version") != status.group(1):
            errs.append(f"quotes: {q.get('section')} stamped {q.get('version')}, market-spec is {status.group(1)}")
    digests = {q["digest"] for q in quotes}
    for section, text in REQUIRED_QUOTES:
        sq = SpecQuote("market-spec.md", section, text)
        if quote_digest(sq) not in digests:
            errs.append(f"quotes: required {section} passage absent from the payload")
        if not check_quote(sq).ok:
            errs.append(f"quotes: required {section} passage no longer matches market-spec.md")
    return errs


def check_generator(payload) -> List[str]:
    from omiecid_simulator.jaxomiecid.omie_tape_synth import construction_digest
    g = payload["generator"]
    errs = []
    if g.get("module") != "omiecid_simulator.jaxomiecid.omie_tape_synth":
        errs.append(f"generator: module {g.get('module')!r}")
    fixture = json.loads((REPO_ROOT / "tests" / "omiecid" / "fixtures" / "cert" / "synth_digests.json")
                         .read_text(encoding="utf-8"))["constructions"][CONSTRUCTION]
    live = construction_digest(CONSTRUCTION)
    if g.get("digests", {}).get(CONSTRUCTION) != live or live != fixture:
        errs.append(f"generator: digest {g.get('digests', {}).get(CONSTRUCTION)} / live {live} / fixture {fixture}")
    return errs


def check_status_consistency(payload) -> List[str]:
    errs = []
    if payload["status"] == "PASS":
        if payload["seeds"]["failing"]:
            errs.append(f"status PASS with failing seeds {payload['seeds']['failing']}")
        if any(a.get("status") != "pass" for a in payload.get("assertions", [])):
            errs.append("status PASS with a failing assertion")
    for a in payload.get("assertions", []):
        if a.get("unit") not in ("price_int", "qty_int", "count", "bool", "other"):
            errs.append(f"assertion {a.get('name')!r}: non-tick unit {a.get('unit')!r}")
    return errs


ALL_CHECKS = (check_schema_and_kinds, check_draw_accounting, check_per_draw_oracle, check_twins,
              check_eager_jit, check_battery, check_capacity, check_dataset_classes, check_quotes,
              check_generator, check_status_consistency)


def audit(payload) -> List[str]:
    out: List[str] = []
    for fn in ALL_CHECKS:
        try:
            out += fn(payload)
        except Exception as exc:  # noqa: BLE001 -- a malformed payload is a finding, not a crash
            out.append(f"{fn.__name__} raised {type(exc).__name__}: {exc}")
    return out


