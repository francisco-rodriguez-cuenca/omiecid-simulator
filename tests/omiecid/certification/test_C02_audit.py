def _results_path() -> Path:
    d = os.environ.get("OMIE_CERT_RESULTS_DIR")
    return (Path(d) if d else DEFAULT_RESULTS_DIR) / "C02.json"


@pytest.fixture(scope="module")
def payload() -> Dict[str, Any]:
    p = _results_path()
    if not p.is_file():
        pytest.skip(f"C02 results JSON absent: {p} (run the C02 notebook or set OMIE_CERT_RESULTS_DIR)")
    return json.loads(p.read_text(encoding="utf-8"))


def _side_name(side: int) -> str:
    from omiecid_simulator.omiecid.order_types import Side
    return "BUY" if int(side) == int(Side.BUY) else "SELL"


@functools.lru_cache(maxsize=None)
def derive(seed: int) -> Dict[str, Any]:
    """The audit's own expectation for one seed, from the regenerated tape only."""
    from omiecid_simulator.jaxomiecid.omie_tape_synth import make_crossing_pair
    from omiecid_simulator.omiecid.order_types import ExecRestriction, Side

    draw = make_crossing_pair(seed)
    tape = draw.tape
    real = tape[tape[:, C_OID] >= 1]
    assert real.shape[0] == 2, f"seed {seed}: crossing pair must have two real rows, has {real.shape[0]}"
    rest, agg = real[0], real[1]
    assert int(rest[C_CONTRACT]) == int(agg[C_CONTRACT]), f"seed {seed}: two contracts"
    assert int(rest[C_SIDE]) != int(agg[C_SIDE]), f"seed {seed}: same side"
    assert int(rest[C_TS]) < int(agg[C_TS]), f"seed {seed}: resting row not earlier"
    for r in (rest, agg):
        assert int(r[C_EXEC]) == int(ExecRestriction.NON), f"seed {seed}: not NON"
    buy, sell = (rest, agg) if int(rest[C_SIDE]) == int(Side.BUY) else (agg, rest)
    p_rest, p_agg = int(rest[C_PRICE]), int(agg[C_PRICE])
    q_rest, q_agg = int(rest[C_QTY]), int(agg[C_QTY])
    crosses = int(sell[C_PRICE]) <= int(buy[C_PRICE])
    gap = (p_agg - p_rest) if int(agg[C_SIDE]) == int(Side.BUY) else (p_rest - p_agg)
    who = {"trades": [], "accepted": [int(rest[C_OID]), int(agg[C_OID])]}
    if crosses:
        who["trades"] = [{"passive_oid": int(rest[C_OID]), "aggressor_oid": int(agg[C_OID]),
                          "buyer_oid": int(buy[C_OID]), "seller_oid": int(sell[C_OID]),
                          "on_aggressor_submission": True}]
    if q_agg == q_rest:
        size = "="
    else:
        size = "<" if q_agg < q_rest else ">"
    return {
        "seed": seed, "p_rest": p_rest, "p_agg": p_agg, "q_rest": q_rest, "q_agg": q_agg,
        "gap": gap, "rest_side": _side_name(rest[C_SIDE]), "agg_side": _side_name(agg[C_SIDE]),
        "n_trades": 1 if crosses else 0,
        "price": p_rest if crosses else None,
        "qty": min(q_rest, q_agg) if crosses else 0,
        "who": who,
        "cls": f"{_side_name(agg[C_SIDE])}/q_agg{size}q_rest",
        "hops_bound": int(draw.capacity_bounds["hops"]),
        "peak_resting_per_side": 1,  # one order per side at most, before and after
        "peak_trades": 1 if crosses else 0,
    }


def _zero_eur_int() -> int:
    from omiecid_simulator.omiecid.encoding import encode_price
    from omiecid_simulator.omiecid.omie_config import OMIEProductConfig
    return int(encode_price(0.0, OMIEProductConfig()))


