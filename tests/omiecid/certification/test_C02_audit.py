def _audit_seeds() -> List[int]:
    """One seed per (aggressor side x size order) class, plus the q_agg == q_rest draw,
    chosen from seeds the payload did NOT run eager-vs-jitted where possible."""
    picked: Dict[str, int] = {}
    for s in range(499, -1, -1):
        picked.setdefault(derive(s)["cls"], s)
    return sorted(picked.values())


@pytest.mark.slow
def test_engine_rerun_matches_derivation_eager_and_jitted():
    """slow: compiles submit_order (jit) and runs it eagerly for ~5 seeds."""
    from tests.omiecid.reference.omie_invariants import compare_records, record_from_draw, run_battery
    from omiecid_simulator.jaxomiecid.omie_tape_synth import make_crossing_pair

    problems: List[str] = []
    for s in _audit_seeds():
        want = derive(s)
        draw = make_crossing_pair(s)
        rec_j = record_from_draw(draw, jit=True)
        rec_e = record_from_draw(draw, jit=False)
        diff = compare_records(rec_j, rec_e)
        if diff:
            problems.append(f"seed {s}: eager != jitted on {diff}")
        fills = rec_j.fills
        if len(fills) != 1:
            problems.append(f"seed {s}: {len(fills)} fills")
            continue
        f = fills[0]
        got = (f.price_int, f.qty_int, f.passive_oid, f.aggressor_oid, f.buyer_oid, f.seller_oid, f.submission)
        t = want["who"]["trades"][0]
        exp = (want["p_rest"], want["qty"], t["passive_oid"], t["aggressor_oid"], t["buyer_oid"],
               t["seller_oid"], 1)
        if got != exp:
            problems.append(f"seed {s} ({want['cls']}): fill {got} != derived {exp}")
        rep = run_battery(rec_j, expects_trade=True)
        if not (rep.passed and rep.valid):
            problems.append(f"seed {s}: battery {rep.statuses()}")
    assert problems == []
