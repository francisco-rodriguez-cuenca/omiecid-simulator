"""OMIE-CERT-C02-1 -- K4 audit twin: the single crossing pair.

Fresh-context audit, high-risk scenario (independence rules 3/4). The expectation
here is re-derived from the specification only: ``docs/omiecid/agile-plan.md`` (the C02
card), ``docs/omiecid/scenario-ladder.md`` §C2 and §"The capacity-validity
precondition", ``docs/omiecid/market-spec.md`` §4.5, §5.1, §6.1, §6.2 and §11.1, and the
Continuous Trading Matching Algorithm §5.1.1 in the regulatory corpus. Draws are
regenerated by seed through the generator's public API (``make_crossing_pair``);
the generator's own ``Draw.expected`` is never read. Assertions run against the
EMITTED results JSON ``C02.json``, whatever its status. The notebook is never
opened, imported or run here.

The rule, as the audit derives it from the tape (row 0 rests, row 1 arrives):

* §6.1 / §6.2 item 2: the pair matches iff they are on opposite sides of one
  contract and $p_{\\text{sell}} \\le p_{\\text{buy}}$ (equality crosses: "best bid
  price ≥ best ask price").
* §6.2 item 3, §11.1, CTMA §5.1.1: the trade price is the limit price of the order
  already in the book, $p = p_{\\text{rest}}$, never $p_{\\text{agg}}$.
* §5.1 / §4.5 (NON, partial fill allowed, quantity reduced by the trade):
  exactly one trade of $q = \\min(q_{\\text{rest}}, q_{\\text{agg}})$; the resting
  order is the passive leg, the arrival the aggressor, and the trade is written by
  the aggressor's submission. Buyer and seller follow the rows' sides.
* No match (one tick short): no trade, both orders rest at their own price and
  quantity (§4.5 NON: book entry if unmatched).
* Capacity (card / I8): at most one order rests per side at any instant and at most
  one trade is written, so the peaks are 1 and 1; the generator's hop bound must be
  ≤ 160 on every draw.

Every check is a function ``payload -> list[str]``; an empty list means clean.
Broken copies of the payload are written to ``tmp_path``, and each one must be
rejected for its own reason. That shows the audit is able to fail.
"""

