def _draw_assertions(payload) -> Dict[int, Dict[str, List[dict]]]:
    out: Dict[int, Dict[str, List[dict]]] = {}
    for a in payload.get("assertions", []):
        if a.get("kind") != "oracle":
            continue
        m = _SEED_RE.match(a.get("name", ""))
        if not m:
            continue
        seed, suffix = int(m.group(1)), m.group(2)
        out.setdefault(seed, {}).setdefault(suffix, []).append(a)
    return out


def _twin_assertions(payload) -> Dict[tuple, Dict[str, List[dict]]]:
    out: Dict[tuple, Dict[str, List[dict]]] = {}
    for a in payload.get("assertions", []):
        m = _TWIN_RE.match(a.get("name", ""))
        if a.get("kind") != "oracle" or not m:
            continue
        out.setdefault((int(m.group(1)), m.group(2)), {}).setdefault(m.group(3), []).append(a)
    return out


def _is_int(x) -> bool:
    return isinstance(x, int) and not isinstance(x, bool)


def _exact(a: dict, want, label: str) -> List[str]:
    errs = []
    if a.get("status") != "pass":
        errs.append(f"{label}: status {a.get('status')!r}")
    for k in ("expected", "observed"):
        v = a.get(k)
        if _is_int(want) and not _is_int(v):
            errs.append(f"{label}: {k} {v!r} is not an integer tick count")
        elif v != want:
            errs.append(f"{label}: {k} {v!r} != audit derivation {want!r}")
    return errs


