def check_quotes(payload) -> List[str]:
    from notebooks.certification.cert_support import SpecQuote, check_quote, quote_digest
    err = []
    quotes = payload["spec"]["quotes"]
    have = {q["digest"] for q in quotes}
    versions = {"market-spec.md": _doc_version("market-spec.md"),
                "scenario-ladder-review.md": _doc_version("scenario-ladder-review.md")}
    for q in quotes:
        if not (q["ok"] is True and q["reason"] == "ok"):
            err.append(f"quote {q['source']} {q['section']} not ok: {q['reason']}")
        want_v = versions.get(q["source"])
        if want_v is not None and q["version"] != want_v:
            err.append(f"quote {q['source']} {q['section']} version {q['version']} != current {want_v}")
    for label, (section, forms) in _MANDATED.items():
        hits = [f for f in forms if quote_digest(SpecQuote("market-spec.md", section, f)) in have]
        if not hits:
            err.append(f"mandated quote missing: {label}")
        for f in hits:
            c = check_quote(SpecQuote("market-spec.md", section, f))
            if not c.ok:
                err.append(f"mandated quote {label} no longer matches market-spec: {c.reason}")
    for f in _FORBIDDEN:
        if quote_digest(SpecQuote("market-spec.md", "§3.3", f)) in have:
            err.append("R-1: the Matching Algorithm §5.5 sentence is quoted as authority")
    return err


