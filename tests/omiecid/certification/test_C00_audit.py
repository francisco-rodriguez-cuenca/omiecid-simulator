def _leaves_equal(a, b) -> List[str]:
    """Paths of the pytree leaves that differ (empty = leaf-for-leaf equal)."""
    import jax
    import numpy as np
    pa = jax.tree_util.tree_flatten_with_path(a)[0]
    pb = jax.tree_util.tree_flatten_with_path(b)[0]
    if [k for k, _ in pa] != [k for k, _ in pb]:
        return ["<tree structure>"]
    return [jax.tree_util.keystr(k) for (k, x), (_, y) in zip(pa, pb)
            if not np.array_equal(np.asarray(x), np.asarray(y))]


@pytest.fixture(scope="module")
def pad_probe() -> Dict[str, Any]:
    """The 64-row pad-only tape replayed through ``Session`` with ``AgentOrder.none()``."""
    import jax
    import numpy as np
    from omiecid_simulator.omiecid.omie_session import AgentOrder, Session

    tape = np.asarray(_synth().make_pad_only().tape)
    assert tape.shape[0] == N_PAD and not (tape[:, _synth().COL_OID] >= 1).any()
    env = Session({"tapes": tape[None], "orders_per_step": 4})
    key = jax.random.PRNGKey(0)
    fresh = env.reset(key)
    st, st_none = fresh, fresh
    reports, dones, mismatch_none = [], [], []
    for k in range(env.steps_per_episode):
        st, rep, done = env.step_env(key, st, AgentOrder.none())
        st_none, rep_none, done_none = env.step(key, st_none, None)
        diff = _leaves_equal((st, rep, done), (st_none, rep_none, done_none))
        if diff:
            mismatch_none.append((k, diff))
        reports.append(rep)
        dones.append(bool(np.asarray(done)))
    trades = np.asarray(st.book.lob.trades)
    return {
        "env": env, "fresh": fresh, "final": st, "reports": reports, "dones": dones,
        "mismatch_none": mismatch_none,
        "rows consumed": int(np.asarray(st.tape_cursor)),
        "orders submitted": sum(int(np.asarray(r.submitted)) for r in reports),
        "fills": int((trades[:, 0] != np.asarray(fresh.book.lob.trades)[:, 0]).sum()),
        "clock advance": int(np.asarray(st.time)) - int(np.asarray(fresh.time)),
        "post-state == its fresh state": _leaves_equal(st.book, fresh.book),
    }


@pytest.mark.slow
@pytest.mark.jit
class TestPadPathThroughSession:
    """slow: compiles ``Session.reset`` / ``step_env`` once (~20-60 s on CPU)."""

    def test_pad_rows_are_consumed_and_inert(self, pad_probe):
        assert pad_probe["rows consumed"] == N_PAD
        assert pad_probe["orders submitted"] == 0
        assert pad_probe["fills"] == 0
        assert pad_probe["clock advance"] == 0
        assert pad_probe["post-state == its fresh state"] == []

    def test_participant_accounting_untouched(self, pad_probe):
        import numpy as np
        fin, fresh = pad_probe["final"], pad_probe["fresh"]
        assert not np.asarray(fin.agent_cash).any()
        assert not np.asarray(fin.agent_inventory).any()
        assert np.array_equal(np.asarray(fin.agent_trades), np.asarray(fresh.agent_trades))
        assert not np.asarray(fin.agent_trades).any()

    def test_every_fill_report_is_empty(self, pad_probe):
        """An inactive order on a pad slice: nothing submitted, no id, no fill, no cash."""
        import jax
        import numpy as np
        for k, rep in enumerate(pad_probe["reports"]):
            assert not bool(np.asarray(rep.submitted)), k
            assert int(np.asarray(rep.order_id)) == 0, k
            for leaf in jax.tree_util.tree_leaves(rep.submit):
                assert not np.asarray(leaf).any(), (k, rep.submit)
            for f in ("passive_qty_signed", "passive_value_eur", "inventory_delta",
                      "cash_delta_eur", "trade_rows"):
                assert not np.asarray(getattr(rep, f)).any(), (k, f)
            assert not bool(np.asarray(rep.trades_saturated)), k

    def test_done_never_raised_by_pad_rows(self, pad_probe):
        """No clock advance, so the clock never reaches GCT: ``done`` stays False."""
        assert pad_probe["dones"] == [False] * pad_probe["env"].steps_per_episode

    def test_none_order_is_the_same_program_as_agent_order_none(self, pad_probe):
        assert pad_probe["mismatch_none"] == []

    def test_fresh_session_state_is_empty(self, pad_probe):
        import numpy as np
        fresh = pad_probe["fresh"]
        lob = fresh.book.lob
        assert int(np.asarray(fresh.book.n_active)) == 0
        assert int(np.asarray(fresh.time)) == 0 and int(np.asarray(fresh.tape_cursor)) == 0
        # no resting order on either side (order id column empty) and no trade
        for side in (np.asarray(lob.bids), np.asarray(lob.asks)):
            assert not (side[:, 2] > 0).any()
        assert pad_probe["fills"] == 0

    def test_emitted_pad_path_records_agree_with_the_probe(self, payload, pad_probe):
        want = {f: pad_probe[f] for f in ("rows consumed", "orders submitted", "fills",
                                          "clock advance", "post-state == its fresh state")}
        for f, v in want.items():
            r = _one(payload, lambda n, f=f: "pad path [jit]" in n and n.endswith(": " + f), f)
            assert r is not None, f"no unique 'pad path [jit]' record {f!r}"
            assert r["observed"] == v, (f, r["observed"], v)
