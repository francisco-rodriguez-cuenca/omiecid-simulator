def check_every_record_honest(payload) -> List[str]:
    """No failing record, and a 'pass' record must have observed == expected."""
    err = []
    for r in _records(payload):
        if r["status"] != "pass":
            err.append(f"record failed: {r['name']}")
        elif r["expected"] != r["observed"]:
            err.append(f"record marked pass with expected != observed: {r['name']}")
    return err


def check_seeds_and_draws(payload) -> List[str]:
    err = []
    s, d = payload["seeds"], payload["draws"]
    seeds = _seeds(payload)
    if s["count"] != len(seeds) or s["count"] < 1:
        err.append(f"seeds.count {s['count']} inconsistent with first..last {s['first']}..{s['last']}")
    if s["failing"]:
        err.append(f"failing seeds: {s['failing']}")
    seen = {k[0] for k in _gate_records(payload)}
    if seen != set(seeds):
        err.append(f"seeds exercised {sorted(seen)} != declared {seeds}")
    # Every draw is deterministic and analytically inside the envelope (see
    # check_capacity), so none can be INVALID: zero discards.
    if d["discarded"] != 0 or d["valid"] != d["requested"]:
        err.append(f"draws: {d} -- a C00 draw cannot breach the envelope, discards must be 0")
    # Minimum: empty + pad-only + one draw per (seed, non-OPEN status).
    if d["requested"] < 2 + len(NON_OPEN) * len(seeds):
        err.append(f"draws.requested {d['requested']} < 2 + 3 x {len(seeds)} seeds")
    return err


def check_generator(payload) -> List[str]:
    S = _synth()
    g = payload["generator"]
    err = []
    if g["module"] != "omiecid_simulator.jaxomiecid.omie_tape_synth":
        err.append(f"generator.module {g['module']!r}")
    if g["digest_schema_version"] != S.DIGEST_SCHEMA_VERSION:
        err.append("generator.digest_schema_version mismatch")
    keys = set(SEEDLESS_KEYS) | {GATE_KEY}
    if set(g["digests"]) != keys:
        err.append(f"generator.digests keys {sorted(g['digests'])} != {sorted(keys)}")
    for k in sorted(keys & set(g["digests"])):
        want = S.construction_digest(k)
        if g["digests"][k] != want:
            err.append(f"generator digest {k}: {g['digests'][k]} != regenerated {want}")
    return err


def _gate_derived(seed: int) -> Dict[str, Any]:
    """The known result for one draw at a non-OPEN status, from the spec alone:
    §5.4 bullet 4 / §3.3 phase 2 reject every order, so nothing is accepted, nothing
    rests, nothing trades, the book stays at ``init`` and no flag is raised."""
    oids = _real_oids(seed)
    n = len(oids)
    return {
        "submissions": n,
        "accepted ids": [],
        "rejected ids": oids,
        "fills": 0,
        "flags raised": [],
        "final state == fresh (leaf for leaf)": [],  # list of differing leaves
        "n_active": 0,
    }


_GATE_OPTIONAL = {
    "engine accepted": lambda n: [False] * n,
    "engine traded qty_int": lambda n: [0] * n,
    "every post-submission state == fresh": lambda n: [],
}


def check_status_gate(payload) -> List[str]:
    err = []
    recs = _gate_records(payload)
    for seed in _seeds(payload):
        derived = _gate_derived(seed)
        n = derived["submissions"]
        for st in NON_OPEN:
            for field, want in derived.items():
                r = recs.get((seed, st, field, "oracle"))
                if r is None:
                    err.append(f"seed {seed} {st}: no record for {field!r}")
                    continue
                if r["seed"] != seed:
                    err.append(f"seed {seed} {st} {field}: record seed {r['seed']}")
                if r["observed"] != want:
                    err.append(f"seed {seed} {st} {field}: observed {r['observed']!r} != derived {want!r}")
                rule = r.get("rule") or ""
                if "§5.4" not in rule and "§3.1" not in rule:
                    err.append(f"seed {seed} {st} {field}: rule {rule!r} does not cite §3.1/§5.4")
            for field, mk in _GATE_OPTIONAL.items():
                r = recs.get((seed, st, field, "oracle"))
                if r is not None and r["observed"] != mk(n):
                    err.append(f"seed {seed} {st} {field}: observed {r['observed']!r} != {mk(n)!r}")
    return err


def check_collapse_observed(payload) -> List[str]:
    """V3-12: the three non-OPEN statuses are one rejection branch -- every
    observed outcome is identical across PENDING, SUSPENDED and CLOSED."""
    err = []
    recs = _gate_records(payload)
    for seed in _seeds(payload):
        fields = {k[2] for k in recs if k[0] == seed and k[1] in NON_OPEN and k[3] == "oracle"}
        for f in sorted(fields):
            obs = [recs[(seed, st, f, "oracle")]["observed"] if (seed, st, f, "oracle") in recs
                   else "<missing>" for st in NON_OPEN]
            if any(o != obs[0] for o in obs):
                err.append(f"seed {seed} {f}: non-OPEN statuses disagree {obs!r}")
    return err


def check_open_control_non_vacuous(payload) -> List[str]:
    """I9: the same draw at OPEN is accepted and trades, so the rejection is the
    gate's doing, not a silently dead tape (a crossing pair: buy limit >= sell limit)."""
    S = _synth()
    err = []
    recs = _gate_records(payload)
    for seed in _seeds(payload):
        tape = _gate_draw(seed).tape
        real = [r for r in tape if int(r[S.COL_OID]) >= 1]
        buys = [int(r[S.COL_PRICE]) for r in real if int(r[S.COL_SIDE]) == int(S.Side.BUY)]
        sells = [int(r[S.COL_PRICE]) for r in real if int(r[S.COL_SIDE]) == int(S.Side.SELL)]
        if not (buys and sells and max(buys) >= min(sells)):
            err.append(f"seed {seed}: regenerated draw does not cross; gate test would be vacuous")
        acc = recs.get((seed, "OPEN", "accepted ids", "oracle"))
        if acc is None or acc["observed"] != _real_oids(seed):
            err.append(f"seed {seed} OPEN: accepted ids {acc and acc['observed']!r} != {_real_oids(seed)}")
        fill = recs.get((seed, "OPEN", "at least one fill", "oracle"))
        if fill is None or fill["observed"] is not True:
            err.append(f"seed {seed} OPEN: no fill observed in the control -> vacuous gate test")
    return err


def check_eager_jit(payload) -> List[str]:
    err = []
    recs = _gate_records(payload)
    for seed in _seeds(payload):
        for st in NON_OPEN + ("OPEN",):
            r = recs.get((seed, st, "eager == jitted", "eager_jit"))
            if r is None or r["observed"] is not True:
                err.append(f"seed {seed} {st}: eager == jitted missing or false")
    for label in ("empty: eager == jitted", "pad-only: eager == jitted", "pad path: eager == jitted"):
        rs = [r for r in _records(payload) if r["kind"] == "eager_jit" and r["name"].endswith(label)]
        if not rs or any(r["observed"] is not True for r in rs):
            err.append(f"{label!r} missing or false")
    return err


def _one(payload, pred, what) -> Optional[Dict[str, Any]]:
    rs = _find(payload, pred)
    return rs[0] if len(rs) == 1 else None


def check_empty_and_fresh(payload) -> List[str]:
    """§C0 first claim: an empty book is empty; a fresh state is reproducible."""
    err = []
    want = {
        "(E0) fresh state is empty": [],
        "(E0) fresh state reproducible: eager == jitted": [],
        "(E0) fresh state reproducible: second build": [],
        "empty: submissions": _synth().make_empty().n_real_rows(),
        "empty: fills": 0,
        "empty: accepted ids": [],
        "empty: flags raised": [],
        "empty: final state == fresh (leaf for leaf)": [],
    }
    for name, v in want.items():
        r = _one(payload, lambda n, name=name: n.endswith(name) and "pad" not in n, name)
        if r is None:
            err.append(f"no unique record {name!r}")
        elif r["observed"] != v:
            err.append(f"{name}: observed {r['observed']!r} != {v!r}")
    return err


def check_pad_inertness(payload) -> List[str]:
    """§C0 second claim (simulator artefact): 64 pad rows are consumed, submit
    nothing, fill nothing, leave the state at its fresh value and advance no clock."""
    err = []
    n_pad = _synth().make_pad_only().params["n_pad"]
    if n_pad != N_PAD:
        err.append(f"generator pad-only n_pad {n_pad} != card's {N_PAD}")
    builder = {"submissions": 0, "fills": 0, "accepted ids": [], "rejected ids": [],
               "flags raised": [], "final state == fresh (leaf for leaf)": []}
    for f, v in builder.items():
        r = _one(payload, lambda n, f=f: "pad-only (builder)" in n and n.endswith(": " + f), f)
        if r is None:
            err.append(f"pad-only (builder): no unique record {f!r}")
        elif r["observed"] != v:
            err.append(f"pad-only (builder) {f}: observed {r['observed']!r} != {v!r}")
    path = {"rows consumed": N_PAD, "orders submitted": 0, "fills": 0, "clock advance": 0,
            "post-state == its fresh state": [], "its fresh state is empty": []}
    for mode in ("[eager]", "[jit]"):
        for f, v in path.items():
            r = _one(payload, lambda n, f=f, mode=mode: f"pad path {mode}" in n and n.endswith(": " + f), f)
            if r is None:
                err.append(f"pad path {mode}: no unique record {f!r}")
            elif r["observed"] != v:
                err.append(f"pad path {mode} {f}: observed {r['observed']!r} != {v!r}")
    # Honesty about provenance: pad-row inertness has no spec section.
    for r in _find(payload, lambda n: "pad-only" in n or "pad path" in n):
        rule = r.get("rule")
        if rule is not None and ("§" in rule or "artefact" not in rule.lower()):
            err.append(f"pad record {r['name']!r} cites {rule!r}; must say simulator artefact, no §")
    return err


def check_battery(payload) -> List[str]:
    err = []
    rows = {row["check_id"]: row for row in payload["invariants"]}
    if set(rows) != set(CHECK_IDS) or len(payload["invariants"]) != len(CHECK_IDS):
        err.append(f"battery rows {sorted(rows)} != full battery {list(CHECK_IDS)}")
    for cid, row in rows.items():
        if row["n_fail"] != 0 or row["status"] == "fail" or row["failing_seeds"]:
            err.append(f"invariant {cid} failed")
    i8, i9 = rows.get("I8"), rows.get("I9")
    if i8 is None or i8["n_pass"] != payload["draws"]["valid"]:
        err.append("I8 must hold on every valid draw (n_pass == draws.valid)")
    if i9 is None or i9["status"] != "pass" or i9["n_pass"] < 1:
        err.append("I9 non-vacuity must pass on at least one draw")
    return err


def check_capacity(payload) -> List[str]:
    err = []
    cap = payload["capacity"]
    if cap["envelope"] != CARD_ENVELOPE:
        err.append(f"capacity.envelope {cap['envelope']} != card {CARD_ENVELOPE}")
    draws = [_gate_draw(s) for s in _seeds(payload)]
    for d in draws:
        for axis, ceiling in CARD_ENVELOPE.items():
            if d.capacity_bounds[axis] > ceiling:
                err.append(f"draw seed {d.seed} bound {axis}={d.capacity_bounds[axis]} > {ceiling}")
    for axis, peak in cap["peaks"].items():
        if peak is None:
            continue
        bound = max(d.capacity_bounds[axis] for d in draws)
        if peak > CARD_ENVELOPE[axis] or peak > bound:
            err.append(f"capacity peak {axis}={peak} exceeds envelope/analytic bound {bound}")
    if not cap["peaks"].get("trades"):
        err.append("capacity peak trades is 0: the OPEN control never traded (vacuous)")
    if cap["peaks"].get("concurrent_icebergs") not in (0, None):
        err.append("C00 tapes carry no iceberg; concurrent_icebergs peak must be 0")
    return err


