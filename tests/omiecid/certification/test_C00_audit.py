def check_citations(payload) -> List[str]:
    """R-1: the phase-2 suspension rests on OMIE Rules §58.2 (e)-(f) and Instruction
    1/2024 §8; each is shown unchecked and its text must exist in the corpus."""
    err = []
    cits = payload["citations"]
    corpus = _corpus_texts()
    for label, (fname, tok1, tok2) in _CITATIONS.items():
        match = [c for c in cits if tok1 in c["source"] and tok2 in c["source"]]
        if len(match) != 1:
            err.append(f"citation {label}: {len(match)} entries (need exactly 1)")
            continue
        c = match[0]
        if c["checked"] is not False:
            err.append(f"citation {label}: checked must be false (corpus is not machine-checked)")
        txt = _ws(c["text"])
        docs = [k for k, v in corpus.items() if k.endswith(fname) and txt in v]
        if not docs:
            err.append(f"citation {label}: text not found verbatim in corpus file {fname}")
    return err


