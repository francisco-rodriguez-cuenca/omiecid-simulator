def audit_errors(payload) -> List[str]:
    out = []
    for chk in ALL_CHECKS:
        try:
            out.extend(chk(payload))
        except Exception as exc:  # noqa: BLE001 -- a malformed payload is an audit failure
            out.append(f"{chk.__name__} raised {exc!r}")
    return out


