def _set_observed(p, pred, value, also_expected=True):
    n = 0
    for r in p["assertions"]:
        if pred(r["name"]):
            r["observed"] = value
            if also_expected:
                r["expected"] = value  # a self-consistent lie: status stays "pass"
            n += 1
    assert n, "mutation matched no record"


def _recompute_quote_digest(p):
    # Aggregate rule R3b (results.schema / validate_results): blake2b-128 of the
    # concatenated per-quote digests -- kept valid so only the audit can object.
    blob = "".join(q["digest"] for q in p["spec"]["quotes"]).encode("utf-8")
    p["spec"]["quote_digest"] = hashlib.blake2b(blob, digest_size=16).hexdigest()


def _m_closed_trades(p):
    _set_observed(p, lambda n: re.search(r"seed 3 CLOSED: fills$", n) is not None, 1)


def _m_suspended_accepts(p):
    _set_observed(p, lambda n: re.search(r"seed 0 SUSPENDED: accepted ids$", n) is not None, [1])
    _set_observed(p, lambda n: re.search(r"seed 0 SUSPENDED: rejected ids$", n) is not None, [2])


def _m_drop_suspended(p):
    p["assertions"] = [r for r in p["assertions"] if "SUSPENDED" not in r["name"]]


def _m_pad_advances_clock(p):
    _set_observed(p, lambda n: "pad path [jit]" in n and n.endswith(": clock advance"), 64)


def _m_pending_state_mutated(p):
    _set_observed(p, lambda n: n.endswith("seed 5 PENDING: final state == fresh (leaf for leaf)"),
                  ["bid_book.price"])


def _m_generator_digest(p):
    p["generator"]["digests"][GATE_KEY] = "0" * 32


def _m_drop_gct_quote(p):
    from notebooks.certification.cert_support import SpecQuote, quote_digest
    bad = {quote_digest(SpecQuote("market-spec.md", "§5.4", f)) for f in _MANDATED["§5.4 bullet 4"][1]}
    p["spec"]["quotes"] = [q for q in p["spec"]["quotes"] if q["digest"] not in bad]
    _recompute_quote_digest(p)


def _m_stale_spec_version(p):
    for q in p["spec"]["quotes"]:
        if q["source"] == "market-spec.md":
            q["version"] = "v2.12"


def _m_vacuous_control(p):
    _set_observed(p, lambda n: n.endswith("OPEN: at least one fill"), False)
    p["capacity"]["peaks"]["trades"] = 0
    for row in p["invariants"]:
        if row["check_id"] == "I9":
            row.update(n_pass=0, n_not_applicable=row["n_pass"] + row["n_not_applicable"],
                       status="not_applicable")


def _m_skip_battery_row(p):
    p["invariants"] = [r for r in p["invariants"] if r["check_id"] != "I5"]


def _m_eager_jit_disagree(p):
    for r in p["assertions"]:
        if r["name"].endswith("seed 2 CLOSED: eager == jitted"):
            r["observed"] = False
            r["status"] = "fail"
    p["status"] = "PASS"  # the notebook would have to lie for this copy to look green


def _m_citation_paraphrased(p):
    for c in p["citations"]:
        if "(e)" in c["source"]:
            c["text"] = c["text"].replace("shall be stopped", "is paused")


def _m_pad_cites_lifecycle(p):
    for r in p["assertions"]:
        if "pad path [eager]" in r["name"]:
            r["rule"] = "§5.1"


