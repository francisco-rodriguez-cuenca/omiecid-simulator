@functools.lru_cache(maxsize=None)
def _synth():
    from omiecid_simulator.jaxomiecid import omie_tape_synth as S
    return S


@functools.lru_cache(maxsize=None)
def _gate_draw(seed: int):
    return _synth().make_status_gate(int(seed))


def _real_oids(seed: int) -> List[int]:
    S = _synth()
    tape = _gate_draw(seed).tape
    return sorted(int(r[S.COL_OID]) for r in tape if int(r[S.COL_OID]) >= 1)


def _doc_version(name: str) -> str:
    text = (DOCS / name).read_text(encoding="utf-8")
    m = re.search(r"^\*\*Status:\*\*\s*(v\d+(?:\.\d+)*)", text, re.M)
    assert m, f"no **Status:** version header in {name}"
    return m.group(1)


def _ws(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


@functools.lru_cache(maxsize=None)
def _corpus_texts() -> Dict[str, str]:
    return {str(p.relative_to(CORPUS)): _ws(p.read_text(encoding="utf-8", errors="replace"))
            for p in CORPUS.rglob("*.md")}


def _records(payload: Mapping[str, Any]) -> List[Dict[str, Any]]:
    return list(payload.get("assertions", []))


_GATE_RE = re.compile(r"seed (\d+) (PENDING|SUSPENDED|CLOSED|OPEN): (.+)$")


def _gate_records(payload) -> Dict[tuple, Dict[str, Any]]:
    """``{(seed, status, field, kind): record}`` for every per-seed status record."""
    out = {}
    for r in _records(payload):
        m = _GATE_RE.search(r["name"])
        if m:
            out[(int(m.group(1)), m.group(2), m.group(3).strip(), r["kind"])] = r
    return out


def _find(payload, pred: Callable[[str], bool]) -> List[Dict[str, Any]]:
    return [r for r in _records(payload) if pred(r["name"])]


def _seeds(payload) -> List[int]:
    s = payload["seeds"]
    return list(range(int(s["first"]), int(s["last"]) + 1))


