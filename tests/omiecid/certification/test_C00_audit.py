@pytest.mark.parametrize("name", sorted(MUTATIONS))
def test_broken_copy_is_rejected(payload, tmp_path, name):
    mutate, needle = MUTATIONS[name]
    broken = copy.deepcopy(payload)
    mutate(broken)
    path = tmp_path / "C00.json"
    path.write_text(json.dumps(broken, ensure_ascii=False), encoding="utf-8")
    reloaded = json.loads(path.read_text(encoding="utf-8"))
    errors = audit_errors(reloaded)
    assert errors, f"broken copy {name!r} passed the audit"
    assert any(needle in e for e in errors), f"{name}: expected an error containing {needle!r}; got {errors[:8]}"


