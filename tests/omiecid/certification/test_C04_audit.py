def test_probe_interior_cancel_keeps_survivor_priority(rest_side):
    """§5.1 / §6.1: touch 3001, 17, 52044, 260 at one price (entry order), a decoy
    beyond the aggressor's limit; cancel the interior 17; an aggressor for 2 lots fills
    3001 then 52044 (not 260), at the touch price; 260 and the decoy rest untouched."""
    agg_side = BUY if rest_side == SELL else SELL
    touch_p, decoy_p = (_PA, _PB) if rest_side == SELL else (_PB, _PA)
