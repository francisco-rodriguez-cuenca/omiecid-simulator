"""OMIE-CERT-C04-1 -- K4 audit twin: cancellation.

Fresh-context audit (independence rules 3/4). The expectation is re-derived here from
the specification only: ``docs/omiecid/agile-plan.md`` (the C04 card),
``docs/omiecid/scenario-ladder.md`` §C4 and §"The capacity-validity precondition",
``docs/omiecid/scenario-ladder-plan.md`` §C4, ``docs/omiecid/market-spec.md`` §4.2, §4.2.1
Rules 1-2, §4.5, §5.1, §5.2, §6.1, §6.2, and ``scenario-ladder-review.md`` N-3 (quote
the whole ``CANCELLED (…)`` branch). Draws are regenerated by seed through the
generator's public API (``make_cancellation``); the generator's ``Draw.expected`` is
never read. Assertions run against the EMITTED results JSON ``C04.json``, whatever its
status. The notebook is never opened, imported or run, and no engine module
(``contract_book``, ``iceberg_manager``, ``order_validator``, ``settlement``) is read.

The rule, as this audit derives it from the tape:

* §5.1 ``IN_BOOK -> CANCELLED (by agent; …)``: a cancel removes exactly the named order,
  its whole remaining quantity (visible + hidden), and nothing else. It is not a
  new-timestamp event (§5.2 lists modification, reactivation and new iceberg slices
  only), so it triggers no matching and prints no trade (§6.2: matching is triggered
  by a new-timestamp order).
* §5.2 / §6.1: the survivors keep their stamps, so they keep their relative priority.
  An aggressor sized for ``j`` touch orders fills the ``j`` earliest remaining
  originals, in entry order, at the touch price (§6.2 item 3); the worse-priced
  decoys, beyond the aggressor's limit, are untouched.
* §4.2 / §4.2.1 Rule 1 / §4.5 FOK: after the iceberg is cancelled, the only crossing
  liquidity is the visible NON orders, ``V``. The FOK asks ``R`` with
  ``V < R <= V + T``: it cannot be filled in full, so it fills nothing, never rests,
  and leaves the book and the trade tape unchanged. In the no-cancel control the
  pre-check sees ``V + T >= R`` and the FOK fills ``R`` exactly, against the iceberg's
  peak, then the visible orders in entry order, then the iceberg's regenerated slices
  (each slice a new timestamp, §4.2, so it queues behind the visible orders).

Re-run r2 (``OMIE-CERT-RERUN-1``, K7-U REPEAT: evidence truncated to ``[:3]``): the
no-cancel control's "every FOK fill ..." record now carries the FULL ``fok_fills`` list
plus a ``departing`` list. The audit asserts the full list fill-for-fill against its own
walk (aggressor, price, quantity, order), that the fills sum to ``R``, that nothing
departs, and that a truncated list is rejected. The spec version is pinned to
market-spec **v2.14**. A few independent engine probes go through ``ContractBook``'s
public API only (``init`` / ``submit_order`` / ``cancel_order``).

Broken engines are modelled as the same walk with another removal or ranking rule:
``swap_with_last`` (the vacated slot is filled by the last array element, ties ranked
by slot) and ``ignore_cancel``. Every check is ``payload -> list[str]``; an empty list
means clean. Broken copies of the payload are written to ``tmp_path`` and each one is
rejected for its own reason.
"""

