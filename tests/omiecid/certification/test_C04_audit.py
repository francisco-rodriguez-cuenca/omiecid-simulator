@functools.lru_cache(maxsize=None)
def _ladder_shape(seed: int) -> Dict[str, Any]:
    """Read the ladder from its tape; ``params`` only names which order is cancelled
    (a scenario input) and is cross-checked against the tape."""
    d = _draw(LAD, seed)
    rows = _rows_of(d.tape)
    agg, resting = rows[-1], rows[:-1]
    tag = f"{LAD} seed {seed}"
    sides = {r["side"] for r in resting}
    assert len(sides) == 1 and agg["side"] not in sides, f"{tag}: sides"
    rest_side = sides.pop()
    best = (min if rest_side == SELL else max)(r["price"] for r in resting)
    touch = [r["oid"] for r in resting if r["price"] == best]
    decoys = [r["oid"] for r in resting if r["price"] != best]
    assert [r["oid"] for r in resting] == touch + decoys, f"{tag}: tape is not touch-then-decoys"
    assert all(r["exec"] == NON for r in rows), f"{tag}: not NON"
    assert [r["ts"] for r in rows] == sorted({r["ts"] for r in rows}), f"{tag}: ts not unique/increasing"
    q_each = {r["qty"] for r in resting}
    assert len(q_each) == 1, f"{tag}: unequal resting quantities"
    q_each = q_each.pop()
    assert _crosses(best, agg), f"{tag}: aggressor does not reach the touch"
    for r in resting:
        if r["oid"] in decoys:
            assert not _crosses(r["price"], agg), f"{tag}: decoy {r['oid']} reachable by price"
    assert agg["qty"] % q_each == 0, f"{tag}: aggressor not sized in whole touch orders"
    j = agg["qty"] // q_each
    k = len(touch)
    assert 2 <= k <= 5 and 1 <= j <= k - 1 and 1 <= len(decoys) <= 3, f"{tag}: k={k} j={j}"
    cancel = int(d.params["cancel_oid"])
    assert cancel in touch, f"{tag}: cancel_oid {cancel} not a touch order"
    assert int(d.meta["cancel_before_row_of_oid"]) == agg["oid"], f"{tag}: cancel not before the aggressor"
    return {"rows": rows, "agg": agg, "rest_side": rest_side, "touch": touch, "decoys": decoys,
            "q_each": q_each, "p_touch": best, "k": k, "j": j, "cancel": cancel}


def _variant_rows(seed: int, variant: Optional[str]) -> Tuple[List[Dict[str, int]], int]:
    """(rows in entry order, victim oid) for a named run.

    ``decoys_first``: the decoys enter before the touch level (entry stamps re-dealt in
    the new order). ``sweep[Ti]`` / ``sweep_df[Ti]``: the i-th touch order (1-based, entry
    order) is the victim, on the base / decoys-first layout."""
    sh = _ladder_shape(seed)
    by_oid = {r["oid"]: r for r in sh["rows"]}
    victim = sh["cancel"]
    df = False
    if variant is None:
        pass
    elif variant == "decoys_first":
        df = True
    else:
        m = _SWEEP_RE.match(variant)
        if not m:
            raise KeyError(variant)
        i = int(m.group(2))
        if not 1 <= i <= sh["k"]:
            raise KeyError(variant)
        victim = sh["touch"][i - 1]
        df = m.group(1) == "sweep_df"
    if not df:
        return [dict(r) for r in sh["rows"]], victim
    order = sh["decoys"] + sh["touch"] + [sh["agg"]["oid"]]
    stamps = sorted(r["ts"] for r in sh["rows"])
    return [{**by_oid[o], "ts": t} for o, t in zip(order, stamps)], victim


def _walk(rows: Sequence[Mapping[str, int]], victim: int, model: str = "rule") -> Dict[str, Any]:
    """Enter ``rows[:-1]`` (all on one side, none crossing), cancel ``victim`` under
    ``model``, then submit the aggressor ``rows[-1]``.

    ``rule``: removal keeps the survivors' order; ties rank by timestamp (§6.1).
    ``swap_with_last``: the last array element moves into the vacated slot; ties rank by
    array slot. ``ignore_cancel``: the cancel is a no-op."""
    book: Dict[int, List[Dict[str, int]]] = {BUY: [], SELL: []}
    for r in rows[:-1]:
        book[r["side"]].append(dict(r))
    agg = rows[-1]
    rest_side = SELL if agg["side"] == BUY else BUY
    arr = book[rest_side]
    i = next(n for n, o in enumerate(arr) if o["oid"] == victim)
    if model == "rule":
        arr.pop(i)
    elif model == "swap_with_last":
        arr[i] = arr[-1]
        arr.pop()
    elif model != "ignore_cancel":
        raise ValueError(model)
    before = {s: [dict(o) for o in book[s]] for s in (BUY, SELL)}

    def key(n_o):
        n, o = n_o
        price_key = o["price"] if rest_side == SELL else -o["price"]
        return (price_key, n if model == "swap_with_last" else o["ts"])

    fills: List[List[Any]] = []
    rem = agg["qty"]
    while rem > 0:
        cands = [(n, o) for n, o in enumerate(arr) if o["qty"] > 0 and _crosses(o["price"], agg)]
        if not cands:
            break
        _, best = min(cands, key=key)
        q = min(rem, best["qty"])
        fills.append([best["oid"], agg["oid"], best["price"], q, True])
        best["qty"] -= q
        rem -= q
    book[rest_side] = [o for o in arr if o["qty"] > 0]
    if rem > 0:
        book[agg["side"]].append({**agg, "qty": rem})
    return {"before": before, "after": book, "fills": fills, "rest_side": rest_side}


def _view(book, cols=("price", "qty", "oid")) -> Dict[str, List[List[int]]]:
    return {name: sorted([o[c] for c in cols] for o in book[s])
            for name, s in (("BUY", BUY), ("SELL", SELL))}


@functools.lru_cache(maxsize=None)
def _derive_cached(seed: int, variant: Optional[str], model: str) -> str:
    rows, victim = _variant_rows(seed, variant)
    w = _walk(rows, victim, model)
    passive = [r for r in rows[:-1] if r["oid"] != victim or model == "ignore_cancel"]
    sh = _ladder_shape(seed)
    out = {
        "victim": victim,
        "victim_qty": sh["q_each"],
        "filled": sorted({f[0] for f in w["fills"]}),
        "seq": w["fills"],
        "book_before": _view(w["before"]),
        "cancel_rows": _view(w["before"], ("price", "qty", "oid", "agent")),
        "book_after": _view(w["after"]),
        "entry_order": [r["oid"] for r in sorted(passive, key=lambda r: r["ts"])],
        "n_fills": len(w["fills"]),
    }
    return json.dumps(out)


def derive(seed: int, variant: Optional[str] = None, model: str = "rule") -> Dict[str, Any]:
    return json.loads(_derive_cached(seed, variant, model))


def _closed_form(seed: int, variant: Optional[str]) -> List[int]:
    """The card's known result: the j earliest remaining originals."""
    sh = _ladder_shape(seed)
    _, victim = _variant_rows(seed, variant)
    return [o for o in sh["touch"] if o != victim][: sh["j"]]


def _swap_separates(seed: int, variant: str) -> bool:
    return derive(seed, variant, "swap_with_last")["seq"] != derive(seed, variant)["seq"]


