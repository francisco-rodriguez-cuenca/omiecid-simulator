@functools.lru_cache(maxsize=None)
def _ice_shape(seed: int) -> Dict[str, Any]:
    d = _draw(ICE, seed)
    rows = _rows_of(d.tape)
    tag = f"{ICE} seed {seed}"
    ice, fok, vis = rows[0], rows[-1], rows[1:-1]
    assert ice["exec"] == ICE_EXEC and ice["peak"] >= 1, f"{tag}: first row is not an iceberg"
    assert fok["exec"] == FOK and fok["side"] != ice["side"], f"{tag}: last row is not an opposite FOK"
    for v in vis:
        assert v["exec"] == NON and v["side"] == ice["side"] and v["price"] == ice["price"], \
            f"{tag}: visible order {v['oid']} not a NON at the iceberg's price"
    assert _crosses(ice["price"], fok), f"{tag}: FOK does not reach the iceberg"
    assert [r["ts"] for r in rows] == sorted({r["ts"] for r in rows}), f"{tag}: ts"
    T, P = ice["qty"], ice["peak"]
    V, R = sum(v["qty"] for v in vis), fok["qty"]
    assert T > P, f"{tag}: iceberg holds no hidden volume (T={T}, P={P})"
    # Non-vacuity of the probe: without the iceberg the FOK cannot fill; with it, it can.
    assert V < R <= V + T, f"{tag}: R={R} not in (V, V+T] = ({V}, {V + T}]"
    assert int(d.params["cancel_oid"]) == ice["oid"], f"{tag}: cancel_oid is not the iceberg"
    assert int(d.meta["cancel_before_row_of_oid"]) == fok["oid"], f"{tag}: cancel not before the FOK"
    return {"rows": rows, "ice": ice, "fok": fok, "vis": vis, "T": T, "P": P, "V": V, "R": R,
            "rest_side": ice["side"], "slices": math.ceil(T / P)}


def _no_cancel_fills(sh) -> List[List[int]]:
    """§4.2.1 Rules 1-2 with §4.2's new timestamp per slice: the FOK takes the
    iceberg's peak, then the visible orders in entry order, then each regenerated slice
    (queued behind them), until R is filled."""
    ice, fok = sh["ice"], sh["fok"]
    queue = [{"oid": ice["oid"], "qty": min(sh["P"], sh["T"]), "ice": True}] + \
            [{"oid": v["oid"], "qty": v["qty"], "ice": False} for v in sh["vis"]]
    hidden = sh["T"] - queue[0]["qty"]
    rem, fills = sh["R"], []
    while rem > 0 and queue:
        head = queue[0]
        q = min(rem, head["qty"])
        fills.append([head["oid"], fok["oid"], ice["price"], q])
        head["qty"] -= q
        rem -= q
        if head["qty"] == 0:
            queue.pop(0)
            if head["ice"] and hidden > 0:
                s = min(sh["P"], hidden)
                hidden -= s
                queue.append({"oid": ice["oid"], "qty": s, "ice": True})
    assert rem == 0
    return fills


