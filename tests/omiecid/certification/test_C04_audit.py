def _tape_from_rows(template, rows):
    import numpy as np
    from omiecid_simulator.jaxomiecid import omie_tape_synth as synth
    real = {int(r[C_OID]): np.array(r) for r in template if int(r[C_OID]) >= 1}
    out = []
    for r in rows:
        row = real[r["oid"]].copy()
        row[C_TS] = r["ts"]
        out.append(row)
    return synth.pad_to(np.array(out, dtype=np.int32), len(out) + 8)


def _fill_seq(rec):
    last = rec.n_submissions - 1
    return [[f.passive_oid, f.aggressor_oid, f.price_int, f.qty_int, f.submission == last]
            for f in rec.fills]


