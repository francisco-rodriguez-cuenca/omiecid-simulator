def _index(payload) -> Dict[Tuple[str, int, Optional[str], str], List[Dict[str, Any]]]:
    idx: Dict[Tuple[str, int, Optional[str], str], List[Dict[str, Any]]] = {}
    for a in payload.get("assertions", []):
        if a.get("kind") != "oracle":
            continue
        m = _NAME_RE.match(a.get("name", ""))
        if m:
            idx.setdefault((m.group(1), int(m.group(2)), m.group(3), m.group(4)), []).append(a)
    return idx


def _one(idx, problems: List[str], key) -> Optional[Dict[str, Any]]:
    got = idx.get(key, [])
    if len(got) != 1:
        problems.append(f"{key}: expected exactly one assertion, found {len(got)}")
        return None
    return got[0]


def _globals(payload) -> Dict[str, Dict[str, Any]]:
    return {a["name"]: a for a in payload["assertions"]
            if a["kind"] == "oracle" and not _NAME_RE.match(a["name"])}


def _sweep_seeds(idx) -> List[int]:
    return sorted({k[1] for k in idx if k[0] == LAD and k[2] and _SWEEP_RE.match(k[2])})


def _sorted_book(obs) -> Optional[Dict[str, List[List[int]]]]:
    if not isinstance(obs, dict) or set(obs) != {"BUY", "SELL"}:
        return None
    try:
        return {s: sorted([int(x) for x in row] for row in obs[s]) for s in ("BUY", "SELL")}
    except (TypeError, ValueError):
        return None


