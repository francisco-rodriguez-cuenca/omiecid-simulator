def _records(p) -> List[Dict[str, Any]]:
    return list(p.get("assertions", []))


def _case_records(p) -> Dict[str, Dict[str, Dict[str, Any]]]:
    """``{class: {suffix: record}}`` for every per-class case record."""
    out: Dict[str, Dict[str, Dict[str, Any]]] = {}
    for r in _records(p):
        cls, sep, suffix = r["name"].partition(": ")
        if sep and suffix in CASE_SUFFIXES:
            out.setdefault(cls, {})[suffix] = r
    return out


_COVER_RE = re.compile(r"^(\d+)/(\d+) seeds( pass)?$")


def _per_draw(values) -> Optional[Dict[int, Any]]:
    """A per-draw field is a list of ``[seed, value]`` pairs; ``None`` if it is not one."""
    if not isinstance(values, list):
        return None
    out: Dict[int, Any] = {}
    for item in values:
        if not (isinstance(item, list) and len(item) == 2 and isinstance(item[0], int)) or item[0] in out:
            return None
        out[item[0]] = item[1]
    return out


def _valid_seeds(p) -> Optional[set]:
    """The valid seeds, when they are determined by the payload (no discards)."""
    s, d = p["seeds"], p["draws"]
    if d["discarded"] == 0 and s["count"]:
        return set(range(int(s["first"]), int(s["last"]) + 1))
    return None


def _rec(p, name: str) -> Optional[Dict[str, Any]]:
    hits = [r for r in _records(p) if r["name"] == name]
    return hits[0] if len(hits) == 1 else None


def _sides(p) -> Dict[int, int]:
    """Per-draw order side, inferred from the submitted right-sign ICEwPI case.

    The emitted payload records no per-draw side (finding, see module report). The
    conforming PPD sign identifies it: PPD < 0 only conforms for a BUY, PPD > 0 only for a
    SELL (§5.4 v2.14). The verdicts of both ICEwPI cases are then re-derived from this side,
    so an engine that ignores the side cannot satisfy both classes on both sides; the
    inference is further cross-checked against the eager record's (seed, side) pairs.
    """
    r = _rec(p, "icewpi_right_sign: submitted unsnapped")
    d = _per_draw(r["observed"]) if r else None
    if not d:
        return {}
    return {seed: (BUY if float(t[4]) < 0 else SELL) for seed, t in d.items() if t[4]}


