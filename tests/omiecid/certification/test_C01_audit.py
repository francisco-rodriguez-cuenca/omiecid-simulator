"""OMIE-CERT-C01-1 -- K4 audit twin: order validation and rejection.

Fresh-context audit (independence rules 3/4). The expectation here is re-derived
from the specification only: ``docs/omiecid/agile-plan.md`` (the C01 card),
``docs/omiecid/scenario-ladder.md`` §C1, ``docs/omiecid/scenario-ladder-plan.md`` §C1 and
§"The capacity-validity precondition", ``docs/omiecid/market-spec.md`` §2.3, §4.2,
§5.1, §5.2, §5.4, ``docs/omiecid/open-questions.md`` OQ-16 and
``docs/omiecid/scenario-ladder-review.md`` §2 / §10. Draws are regenerated by seed
through the generator's public API. Assertions run against the EMITTED results
JSON ``C01.json``, whatever its status. The notebook is never opened or run here.

The rule, as the audit derives it:

* §2.3: price in [-9,999, +9,999] EUR/MWh on a 0.01 tick; quantity in
  [0.1, 999] MW on a 0.1 tick. In integer ticks offset from the price floor,
  $n_p \\in [0, 1\\,999\\,800]$ and $n_q \\in [1, 9\\,990]$.
* The validator snaps to the tick grid first (scenario-ladder §C1), so
  $n = \\operatorname{nint}(x / \\mathit{tick})$; a sub-half-tick offset is accepted,
  and an offset of half a tick or more commits to the next tick and is then bound-checked.
* Iceberg (§4.2, derived): $0 < n_k \\le n_q$.
* §5.4, implemented subset: reject outside the bounds. Guarantee and TSO
  unavailability are not implemented and must be named as non-coverage.
* §5.4 (market-spec v2.14): an iceberg with a non-zero PPD of the wrong sign is
  rejected (BUY PPD > 0, SELL PPD < 0); PPD = 0 is always valid on that check;
  a peak larger than the total is rejected, a peak equal to it is valid.
* On reject, the book is byte-identical (M4 no-mutation). No case trades.

r2 re-audit (OMIE-CERT-RERUN-1 correction): the one-tick-peak control is bounded to
<= 64 slices; eager runs on the first valid seeds; every case records per-draw
integers (``[seed, value]`` lists), which are checked draw by draw against the
snapped integers re-derived here; a wrong-sign ICEwPI rejection case (with a
right-sign control) is present on both sides. A few engine probes exercise the
sign rule through ``ContractBook``'s public API.

Every check is a function ``payload -> list[str]``; an empty list means clean.
Broken copies of the payload are written to ``tmp_path``, and each one must be
rejected for its own reason. That shows the audit is able to fail.
"""

