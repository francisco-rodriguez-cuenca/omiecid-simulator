def _num(s: str) -> Fraction:
    return Fraction(s.replace(",", ""))


@functools.lru_cache(maxsize=1)
def spec_bounds() -> Dict[str, Fraction]:
    text = (DOCS / "market-spec.md").read_text(encoding="utf-8")
    sec = text[text.index("### 2.3 Price and quantity constraints"):text.index("### 2.4")]
    m = re.search(r"Price bounds:\*\* −([\d,.]+) EUR/MWh \(minimum\) to \+([\d,.]+) EUR/MWh", sec)
    t = re.search(r"Price tick \(minimum increment\):\*\* ([\d.]+) EUR/MWh", sec)
    q = re.search(r"Quantity bounds:\*\* ([\d.]+) MW \(minimum\) to ([\d,.]+) MW", sec)
    k = re.search(r"Quantity tick \(minimum increment\):\*\* ([\d.]+) MW", sec)
    assert m and t and q and k, "market-spec §2.3 bounds bullets not found"
    return {"price_min": -_num(m.group(1)), "price_max": _num(m.group(2)), "price_tick": _num(t.group(1)),
            "qty_min": _num(q.group(1)), "qty_max": _num(q.group(2)), "qty_tick": _num(k.group(1))}


def _nint(x: Fraction) -> int:
    """Nearest integer; a half-tick tie is outside the certified domain."""
    lo = x.numerator // x.denominator
    frac = x - lo
    if frac == Fraction(1, 2):
        raise ValueError(f"half-tick tie at {x}")
    return lo + 1 if frac > Fraction(1, 2) else lo


def int_bounds() -> Dict[str, int]:
    b = spec_bounds()
    return {"price_hi": int((b["price_max"] - b["price_min"]) / b["price_tick"]),
            "qty_lo": int(b["qty_min"] / b["qty_tick"]), "qty_hi": int(b["qty_max"] / b["qty_tick"])}


def rule_snap(case: Mapping[str, Any], side: Optional[int] = None) -> Tuple[bool, int, int, Optional[int]]:
    """(accept, n_p, n_q, n_k) for one case, from market-spec v2.14 §2.3 / §4.2 / §5.4 alone.

    ``n_k`` is ``None`` for a non-iceberg (no ``peak_qty_mw`` or a null one). The §5.4 (v2.14)
    sign rule applies to an iceberg with a non-zero PPD: BUY needs PPD < 0, SELL needs PPD > 0;
    PPD = 0 is a standard iceberg and always valid on that check. The side is needed only then.
    """
    b, ib = spec_bounds(), int_bounds()
    n_p = _nint((Fraction(float(case["price_eur"])) - b["price_min"]) / b["price_tick"])
    n_q = _nint(Fraction(float(case["qty_mw"])) / b["qty_tick"])
    ok = 0 <= n_p <= ib["price_hi"] and ib["qty_lo"] <= n_q <= ib["qty_hi"]
    n_k = None
    if case.get("peak_qty_mw") is not None:
        n_k = _nint(Fraction(float(case["peak_qty_mw"])) / b["qty_tick"])
        ok = ok and 0 < n_k <= n_q
        ppd = float(case.get("ppd_eur") or 0.0)
        if ppd != 0.0:
            if side not in (BUY, SELL):
                raise ValueError("ICEwPI case without a side: the sign rule cannot be evaluated")
            ok = ok and ((side == BUY and ppd < 0) or (side == SELL and ppd > 0))
    return ok, n_p, n_q, n_k


def rule_verdict(case: Mapping[str, Any], side: Optional[int] = None) -> Tuple[bool, int]:
    """(accept, snapped n_p) for one case."""
    ok, n_p, _, _ = rule_snap(case, side)
    return ok, n_p


def _case_from_submitted(tup) -> Dict[str, Any]:
    """The emitted 'submitted unsnapped' value is ``[oid, price_eur, qty_mw, peak_mw|null, ppd_eur|null]``."""
    _oid, price, qty, peak, ppd = tup
    return {"price_eur": price, "qty_mw": qty, "peak_qty_mw": peak, "ppd_eur": ppd}


@functools.lru_cache(maxsize=1)
def _synth():
    from omiecid_simulator.jaxomiecid import omie_tape_synth as S
    return S


@functools.lru_cache(maxsize=None)
def _generator_verdicts(first: int, last: int) -> Dict[str, Dict[int, bool]]:
    """``{class: {seed: accept}}`` re-derived for every drawn seed."""
    out: Dict[str, Dict[int, bool]] = {}
    for seed in range(first, last + 1):
        for case in _synth().make_validation_cases(seed).params["cases"]:
            out.setdefault(case["name"], {})[seed] = rule_verdict(case)[0]
    return out


