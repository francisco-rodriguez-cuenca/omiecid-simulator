def check_identity(p) -> List[str]:
    err = []
    for k, v in {"cert_id": "C01", "notebook": "C01_order_validation.ipynb"}.items():
        if p.get(k) != v:
            err.append(f"identity: {k} = {p.get(k)!r}, expected {v!r}")
    ok_kind = p.get("oracle_kind", "")
    if "exact-parametric" not in ok_kind or "M4" not in ok_kind:
        err.append(f"identity: oracle_kind {ok_kind!r} is not exact-parametric reusing M4")
    ib = int_bounds()
    kr = p.get("known_result", "").replace(",", "")
    for label, n in (("price_hi", ib["price_hi"]), ("qty_hi", ib["qty_hi"])):
        if str(n) not in kr:
            err.append(f"known_result does not state the spec-derived bound {label}={n}")
    return err


def check_status_consistency(p) -> List[str]:
    from notebooks.certification.cert_support import derive_failure_kinds
    err = []
    derived = derive_failure_kinds(p)
    if p["failure_kinds"] != derived:
        err.append(f"status: failure_kinds {p['failure_kinds']} != derived from payload {derived}")
    if (p["status"] == "PASS") != (p["failure_kinds"] == []):
        err.append(f"status: {p['status']!r} inconsistent with failure_kinds {p['failure_kinds']}")
    fe = p["failure_explanation"]
    if (fe is None) != (p["status"] == "PASS"):
        err.append("status: failure_explanation must be null exactly when status is PASS")
    if fe is not None:
        d = p["draws"]
        if "capacity_flag" in p["failure_kinds"] and f"{d['valid']} of {d['requested']}" not in fe["what_failed"]:
            err.append("status: capacity_flag explanation does not state valid-of-requested")
        if p["cert_id"] not in fe["paragraph"] or "NOT CERTIFIED" not in fe["paragraph"]:
            err.append("status: failure paragraph does not name the scenario and verdict")
    return err


def check_draws_and_seeds(p) -> List[str]:
    err = []
    d, s = p["draws"], p["seeds"]
    if d["requested"] != CARD_DEFAULT_DRAWS:
        err.append(f"draws: requested {d['requested']} != card default {CARD_DEFAULT_DRAWS}")
    if d["valid"] + d["discarded"] != s["count"]:
        err.append(f"draws: valid {d['valid']} + discarded {d['discarded']} != seeds drawn {s['count']} "
                   "(each drawn seed must be exactly one of valid or discarded)")
    if s["count"] and (s["first"] is None or s["last"] - s["first"] + 1 != s["count"]):
        err.append(f"draws: seeds {s['first']}..{s['last']} not contiguous with count {s['count']}")
    denom = d["valid"] + d["discarded"]
    if denom and abs(d["discard_rate"] - d["discarded"] / denom) > 1e-12:
        err.append(f"draws: discard_rate {d['discard_rate']} != {d['discarded']}/{denom}")
    if d["valid"] == 0:
        err.append("draws: no valid draw -- nothing was certified")
    fail_seeds = {r["seed"] for r in _records(p) if r["status"] == "fail" and r["seed"] is not None}
    for row in p["invariants"]:
        fail_seeds.update(row["failing_seeds"])
    if sorted(fail_seeds) != sorted(s["failing"]):
        err.append(f"draws: seeds.failing {s['failing']} != seeds of failing records {sorted(fail_seeds)}")
    return err


def check_generator(p) -> List[str]:
    S = _synth()
    g = p["generator"]
    err = []
    if g["module"] != "omiecid_simulator.jaxomiecid.omie_tape_synth":
        err.append(f"generator: module {g['module']!r}")
    if g["digest_schema_version"] != S.DIGEST_SCHEMA_VERSION:
        err.append("generator: digest schema version drifted")
    want = S.construction_digest(CONSTRUCTION)
    if g["digests"].get(CONSTRUCTION) != want:
        err.append(f"generator digest for {CONSTRUCTION}: {g['digests'].get(CONSTRUCTION)!r} != regenerated {want!r}")
    return err


def check_product_config(p) -> List[str]:
    b = spec_bounds()
    recs = [r for r in _records(p) if r["name"].startswith("OMIEProductConfig equals §2.3")]
    if len(recs) != 1:
        return [f"product config: expected one §2.3 config record, found {len(recs)}"]
    r = recs[0]
    err = []
    for side in ("expected", "observed"):
        got = r[side] or {}
        for k, v in b.items():
            try:
                ok = Fraction(str(got.get(k))) == v
            except (ValueError, ZeroDivisionError):
                ok = False
            if not ok:
                err.append(f"product config: {side} {k} = {got.get(k)!r}, spec §2.3 says {v}")
    if r["status"] != "pass" and not err:
        err.append("product config: record failed although spec and observation agree")
    return err


def check_class_coverage(p) -> List[str]:
    have = set(_case_records(p))
    err = [f"class coverage: card class {label!r} not exercised (none of {list(names)})"
           for label, names in CARD_CLASSES.items() if not any(n in have for n in names)]
    for name in sorted(have - set(RULE_VERDICT)):
        err.append(f"class coverage: unknown case class {name!r} -- no rule-derived verdict")
    return err


def check_verdicts_match_rules(p) -> List[str]:
    """Each class's recorded accept/reject direction is what the rules imply."""
    err = []
    s = p["seeds"]
    gen = _generator_verdicts(int(s["first"]), int(s["last"])) if s["count"] else {}
    for name, verdicts in gen.items():
        vals = set(verdicts.values())
        if len(vals) != 1:
            err.append(f"generator class {name}: rule verdict varies across seeds -- per-class records cannot stand per draw")
        elif name in RULE_VERDICT and vals != {RULE_VERDICT[name]}:
            err.append(f"generator class {name}: per-seed rule verdict {vals} != class rule {RULE_VERDICT[name]}")
    for name, recs in _case_records(p).items():
        if name not in RULE_VERDICT:
            continue
        accept = RULE_VERDICT[name]
        want = (ACCEPT_SUFFIXES if accept else REJECT_SUFFIXES) + COMMON_SUFFIXES
        forbid = REJECT_SUFFIXES if accept else ACCEPT_SUFFIXES
        word = "accept" if accept else "reject"
        for suf in want:
            if suf not in recs:
                err.append(f"verdict: {name} (rule: {word}) lacks record '{suf}'")
        for suf in forbid:
            if suf in recs:
                err.append(f"verdict: {name} (rule: {word}) records '{suf}' -- wrong direction")
    for label in ("background: accepted and resting", "background: accepted on the integer tape"):
        if not any(r["name"] == label for r in _records(p)):
            err.append(f"verdict: control record {label!r} missing")
    return err


def check_outcomes_match_rules(p) -> List[str]:
    """On the valid draws, the simulator's outcome equals the rule (no class record failed)."""
    return [f"outcome: {r['name']} failed on seed {r['seed']}: expected {r['expected']!r}, observed {r['observed']!r}"
            for r in _records(p) if r["kind"] == "oracle" and r["status"] == "fail"]


def check_per_draw_coverage(p) -> List[str]:
    """Every per-class record covers every valid draw, one ``[seed, value]`` entry per draw (r2)."""
    err = []
    valid = p["draws"]["valid"]
    vseeds = _valid_seeds(p)
    for r in _records(p):
        cls = r["name"].partition(": ")[0]
        if not (cls in RULE_VERDICT or cls in ("background", "run")) or ": " not in r["name"]:
            continue
        m = _COVER_RE.match(r["detail"])
        if not m:
            err.append(f"coverage: {r['name']} has no N/N seeds detail")
        elif not (int(m.group(1)) == int(m.group(2)) == valid):
            err.append(f"coverage: {r['name']} covers {r['detail']}, valid draws = {valid}")
        for side in ("expected", "observed"):
            d = _per_draw(r[side])
            if d is None:
                err.append(f"coverage: {r['name']} {side} is not a per-draw [seed, value] list")
            elif len(d) != valid or (vseeds is not None and set(d) != vseeds):
                err.append(f"coverage: {r['name']} {side} holds {len(d)} draws, valid draws = {valid}")
    return err


def check_integer_evidence(p) -> List[str]:
    """Card: 'on accept, the exact snapped integer the order enters with' -- recorded per draw (r2)."""
    err = []
    for r in _records(p):
        if r["unit"] not in ("price_int", "qty_int"):
            continue
        for side in ("expected", "observed"):
            d = _per_draw(r[side])
            if d is None:
                err.append(f"integer evidence: {r['name']} {side} is not recorded per draw")
                continue
            bad = sorted(s for s, v in d.items() if not (isinstance(v, int) and not isinstance(v, bool)))
            if bad:
                err.append(f"integer evidence: {r['name']} {side} is not an integer on seeds {bad[:10]} "
                           "-- the exact snapped integer is not recorded, so it cannot be audited")
    return err


def check_per_draw_outcomes(p) -> List[str]:
    """Per draw, re-derive the verdict and the snapped integers from the submitted case, and
    compare them with what the run observed (float path, integer tape, book, trades)."""
    err: List[str] = []
    sides = _sides(p)
    for cls, recs in sorted(_case_records(p).items()):
        sub = recs.get("submitted unsnapped")
        if sub is None:
            err.append(f"per-draw: {cls} lacks its 'submitted unsnapped' record")
            continue
        sub_o, sub_e = _per_draw(sub["observed"]), _per_draw(sub["expected"])
        if sub_o is None or sub_e is None:
            err.append(f"per-draw: {cls} submitted case not recorded per draw")
            continue
        views = {k: (_per_draw(v["observed"]), _per_draw(v["expected"])) for k, v in recs.items()}
        bad: Dict[str, List[int]] = {}

        def flag(what: str, seed: int):
            bad.setdefault(what, []).append(seed)

        for seed, tup in sorted(sub_o.items()):
            if tup != sub_e.get(seed):
                flag("submitted != built", seed)
            try:
                ok, n_p, n_q, n_k = rule_snap(_case_from_submitted(tup), sides.get(seed))
            except (ValueError, TypeError) as exc:
                flag(f"rule not evaluable ({exc})", seed)
                continue
            if cls in RULE_VERDICT and ok != RULE_VERDICT[cls]:
                flag(f"draw outside its class (rule: {'accept' if ok else 'reject'})", seed)
            fo = views.get("verdict (float path)", (None, None))[0] or {}
            if fo.get(seed) is not ok:
                flag(f"float-path verdict != rule {ok}", seed)
            to = views.get("verdict (integer tape)", (None, None))[0] or {}
            if seed not in to or (to[seed] == "accepted") != ok:
                flag(f"integer-tape verdict != rule {ok}", seed)
            nt = views.get("no trade written", (None, None))[0] or {}
            if nt.get(seed) != 0:
                flag("trade written", seed)
            if ok:
                want = {"entered price_int": n_p,
                        "visible qty_int": n_q if n_k is None else n_k,
                        "hidden qty_int": 0 if n_k is None else n_q - n_k}
                for suf, w in want.items():
                    o, e = views.get(suf, (None, None))
                    if not o or not e or o.get(seed) != w or e.get(seed) != w:
                        flag(f"{suf} != spec-derived integer", seed)
            else:
                o, e = views.get("book byte-identical on reject", (None, None))
                if not o or not e or o.get(seed) != [] or e.get(seed) != []:
                    flag("book not byte-identical on reject", seed)
        for what, seeds in bad.items():
            err.append(f"per-draw: {cls}: {what} on {len(seeds)} draw(s), first seeds {seeds[:8]}")
    return err


def check_icewpi_sign(p) -> List[str]:
    """r2 correction: a wrong-sign ICEwPI rejection case, exercised on both sides."""
    err = []
    sides = _sides(p)
    r_right = _rec(p, "icewpi_right_sign: submitted unsnapped")
    r_wrong = _rec(p, "icewpi_wrong_sign: submitted unsnapped")
    if not r_right or not r_wrong:
        return ["icewpi: the wrong-sign case and its right-sign control are not both recorded"]
    right, wrong = _per_draw(r_right["observed"]) or {}, _per_draw(r_wrong["observed"]) or {}
    for seed, t in sorted(wrong.items()):
        rt = right.get(seed)
        if t[3] is None or rt is None or rt[3] is None:
            err.append(f"icewpi: seed {seed}: the ICEwPI cases are not icebergs")
            break
        if not t[4] or not rt[4] or (float(t[4]) > 0) == (float(rt[4]) > 0):
            err.append(f"icewpi: seed {seed}: wrong-sign PPD {t[4]} is not the opposite non-zero sign "
                       f"of the right-sign PPD {rt[4]}")
            break
    got = set(sides.values())
    if got != {BUY, SELL}:
        err.append(f"icewpi: the sign rule is exercised on sides {sorted(got)} only -- both BUY and SELL needed")
    eg = _rec(p, "eager runs on the first valid seeds (one per side)")
    if eg is None or not isinstance(eg["observed"], dict):
        err.append("icewpi/eager: the eager-seed record (one per side) is missing")
    else:
        for seed, sd in zip(eg["observed"].get("seeds", []), eg["observed"].get("sides", [])):
            if sides.get(seed) != sd:
                err.append(f"icewpi/eager: eager seed {seed} reported as side {sd}, "
                           f"the submitted ICEwPI PPD implies side {sides.get(seed)}")
    return err


def check_slice_margin(p) -> List[str]:
    """r2 correction: every accepted iceberg, in particular the one-tick-peak control, has
    $\\lceil n_q / n_k \\rceil \\le 64$ slices on every draw."""
    err = []
    sides = _sides(p)
    worst: Dict[int, int] = {}
    for cls, recs in _case_records(p).items():
        sub = recs.get("submitted unsnapped")
        d = _per_draw(sub["observed"]) if sub else None
        for seed, tup in (d or {}).items():
            try:
                ok, _, n_q, n_k = rule_snap(_case_from_submitted(tup), sides.get(seed))
            except (ValueError, TypeError):
                continue
            if ok and n_k is not None:
                slices = -(-n_q // n_k)
                worst[seed] = max(worst.get(seed, 0), slices)
                if cls == "iceberg_peak_one_tick" and n_k != 1:
                    err.append(f"slice margin: iceberg_peak_one_tick seed {seed} has peak {n_k} ticks, not 1")
    over = sorted(s for s, v in worst.items() if v > SLICE_MARGIN)
    if over:
        err.append(f"slice margin: accepted iceberg over {SLICE_MARGIN} slices on seeds {over[:10]} "
                   f"(max {max(worst.values())})")
    if not worst:
        err.append("slice margin: no accepted iceberg found")
    m = [r for r in _records(p) if r["name"].startswith("dataset: every accepted iceberg within the slice margin")]
    if len(m) != 1:
        err.append("slice margin: the pre-run margin record is missing")
    else:
        obs = _per_draw(m[0]["observed"])
        if obs is None or obs != worst:
            diff = sorted(s for s in set(worst) | set(obs or {}) if (obs or {}).get(s) != worst.get(s))
            err.append(f"slice margin: recorded per-draw slice counts differ from ceil(n_q/n_k) on seeds {diff[:10]}")
    return err


def check_eager_jit(p) -> List[str]:
    """Card common rule: the eager and jitted runs agree, eager on the first VALID seeds (r2)."""
    recs = [r for r in _records(p) if r["kind"] == "eager_jit"]
    err = []
    if not recs or p["eager_jit_identical"] is None:
        err.append("eager == jitted: no eager-vs-jitted comparison recorded (card common pass criterion)")
    bad = [r["name"] for r in recs if r["status"] != "pass"]
    if bad:
        err.append(f"eager == jitted: disagreement in {bad}")
    if p["eager_jit_identical"] is not None and p["eager_jit_identical"] != (not bad and bool(recs)):
        err.append("eager == jitted: eager_jit_identical inconsistent with its records")
    sides = _sides(p)
    vseeds = _valid_seeds(p)
    if vseeds is not None and sides:
        first = sorted({min(s for s in vseeds if sides.get(s) == sd) for sd in set(sides.values())})
        ran = sorted({r["seed"] for r in recs})
        if ran != first:
            err.append(f"eager == jitted: eager ran on seeds {ran}, the first valid seed per side is {first}")
    return err


def check_battery(p) -> List[str]:
    err = []
    rows = {r["check_id"]: r for r in p["invariants"]}
    missing = [c for c in CHECK_IDS if c not in rows]
    if missing:
        err.append(f"full battery: rows missing {missing}")
    valid = p["draws"]["valid"]
    for cid, r in rows.items():
        if r["n_pass"] + r["n_fail"] + r["n_not_applicable"] != valid:
            err.append(f"full battery: {cid} counts sum to "
                       f"{r['n_pass'] + r['n_fail'] + r['n_not_applicable']}, valid draws = {valid}")
    for cid in ("I8", "I9"):
        r = rows.get(cid)
        if r is not None and (r["status"] != "pass" or r["n_pass"] != valid):
            err.append(f"full battery: {cid} must pass on every valid draw, got {r['status']} "
                       f"({r['n_pass']}/{valid})")
    return err


def check_capacity(p) -> List[str]:
    err = []
    cap = p["capacity"]
    if cap["envelope"] != CARD_ENVELOPE:
        err.append(f"capacity: envelope {cap['envelope']} != card {CARD_ENVELOPE}")
    for axis, v in cap["peaks"].items():
        if v is not None and v > CARD_ENVELOPE[axis]:
            err.append(f"capacity: valid-draw peak {axis}={v} exceeds the envelope {CARD_ENVELOPE[axis]}")
    if cap["peaks"].get("trades") not in (0, None):
        err.append(f"capacity: trades peak {cap['peaks']['trades']} -- no validation case may trade")
    return err


