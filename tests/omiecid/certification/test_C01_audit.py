def _leaves_equal(a, b) -> bool:
    import jax
    import numpy as np
    la, lb = jax.tree_util.tree_leaves(a), jax.tree_util.tree_leaves(b)
    return len(la) == len(lb) and all(
        np.asarray(x).dtype == np.asarray(y).dtype and np.array_equal(np.asarray(x), np.asarray(y))
        for x, y in zip(la, lb))


def _probe_order(side: int, ppd: float, qty: float = 2.0, peak: float = 1.0, oid: int = 11):
    from omiecid_simulator.omiecid.order_types import ExecRestriction, Side, make_order
    return make_order(contract_id=37, side=Side(side), price=50.00, quantity=qty, order_id=oid,
                      agent_id=3, timestamp=100, exec_restriction=ExecRestriction.ICE,
                      peak_qty=peak, ppd=ppd)


# (side, ppd, qty, peak); the verdict is derived by rule_verdict (§5.4 v2.14 / §4.2), not hard-coded
_PROBES = {
    "buy_ppd_negative": (BUY, -0.01, 2.0, 1.0),
    "buy_ppd_positive_wrong_sign": (BUY, 0.01, 2.0, 1.0),
    "sell_ppd_positive": (SELL, 0.01, 2.0, 1.0),
    "sell_ppd_negative_wrong_sign": (SELL, -0.01, 2.0, 1.0),
    "buy_ppd_zero_standard_iceberg": (BUY, 0.0, 2.0, 1.0),
    "sell_ppd_zero_standard_iceberg": (SELL, 0.0, 2.0, 1.0),
    "buy_ppd_large_magnitude_unbounded": (BUY, -3.00, 2.0, 1.0),
    "sell_wrong_sign_and_peak_eq_total": (SELL, -0.01, 2.0, 2.0),
    "buy_right_sign_peak_over_total": (BUY, -0.01, 2.0, 2.1),
}


@pytest.mark.jit
@pytest.mark.slow  # slow: the first call compiles the jitted submit_order (one compile per worker)
@pytest.mark.parametrize("probe", sorted(_PROBES))
def test_engine_probe_icewpi_sign_and_peak(book, empty_state, probe):
    side, ppd, qty, peak = _PROBES[probe]
    want = rule_verdict({"price_eur": 50.00, "qty_mw": qty, "peak_qty_mw": peak, "ppd_eur": ppd}, side)[0]
    state, res = book.submit_order(empty_state, _probe_order(side, ppd, qty, peak))
    assert bool(res.accepted) is want, f"{probe}: accepted={bool(res.accepted)}, §5.4 rule says {want}"
    assert bool(res.traded) is False
    if want:
        found = book.get_order(state, 11, side)
        assert int(found.order_id) == 11 and abs(float(found.price) - 50.00) < 1e-6
    else:
        assert _leaves_equal(state, empty_state), f"{probe}: rejected order mutated the book (M4)"


@pytest.mark.jit
@pytest.mark.slow  # slow: the first call compiles the jitted submit_order (one compile per worker)
def test_engine_probe_wrong_sign_reject_leaves_populated_book_unchanged(book, empty_state):
    """A wrong-sign reject on a non-empty book (a right-sign ICEwPI already resting) is a no-op."""
    s1, r1 = book.submit_order(empty_state, _probe_order(SELL, 0.05, oid=21))
    assert bool(r1.accepted) is True
    s2, r2 = book.submit_order(s1, _probe_order(BUY, 0.05, oid=22))   # BUY with PPD > 0
    assert bool(r2.accepted) is False and bool(r2.traded) is False
    assert _leaves_equal(s2, s1)
