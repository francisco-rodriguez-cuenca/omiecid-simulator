def _side_arr(state, side: int) -> np.ndarray:
    return np.asarray(state.lob.bids if side == BUY else state.lob.asks)


def _live(state, side: int) -> np.ndarray:
    a = _side_arr(state, side)
    return a[(a[:, _OID] > 0) & (a[:, _Q] > 0)]


def _row_of(state, side: int, oid: int) -> np.ndarray:
    a = _live(state, side)
    rows = a[a[:, _OID] == oid]
    assert len(rows) == 1, f"oid {oid}: expected exactly 1 live row, got {rows.tolist()}"
    return rows[0]


def _has(state, side: int, oid: int) -> bool:
    return bool((_live(state, side)[:, _OID] == oid).any())


def _key(state, side: int, oid: int) -> Tuple[int, int]:
    """Stored entry stamp ``(SEC, NSEC)`` of ``oid``'s live row on ``side``."""
    r = _row_of(state, side, oid)
    return int(r[_SEC]), int(r[_NSEC])


def _trades(state) -> np.ndarray:
    t = np.asarray(state.lob.trades)
    return t[t[:, _T_P] > 0]


def _tape_saturated(state) -> bool:
    return len(_trades(state)) >= np.asarray(state.lob.trades).shape[0]


def _new_trades(run: Run, i: int) -> List[Tuple[int, int, int, int]]:
    """(P, |Q|, PASS_OID, AGRS_OID) of the tape rows written by step ``i``
    (unsaturated tape: rows are appended)."""
    n0 = len(_trades(run.pre_states[i]))
    return [(int(r[_T_P]), abs(int(r[_T_Q])), int(r[_T_PASS_OID]),
             int(r[_T_AGRS_OID])) for r in _trades(run.states[i])[n0:]]


def _all_live_keys(state) -> List[Tuple[int, int, int, int]]:
    """(SEC, NSEC, side, OID) of every live row on both sides."""
    out = []
    for side in (BUY, SELL):
        for r in _live(state, side):
            out.append((int(r[_SEC]), int(r[_NSEC]), side, int(r[_OID])))
    return out


def _duplicate_stamps(state) -> List[Tuple[int, int]]:
    """``(SEC, NSEC)`` keys held by two or more live rows of the contract
    (both sides, every price)."""
    seen: Dict[Tuple[int, int], int] = {}
    for sec, nsec, _s, _o in _all_live_keys(state):
        seen[(sec, nsec)] = seen.get((sec, nsec), 0) + 1
    return sorted(k for k, c in seen.items() if c > 1)


def _fixture(name: str) -> Path:
    for d in _FIXTURE_CANDIDATES:
        if (d / name).is_file():
            return d / name
    raise AssertionError(f"fixture missing: {name} (looked in {_FIXTURE_CANDIDATES})")


def _fixture_rows(name: str) -> List[np.ndarray]:
    z = np.load(_fixture(name), allow_pickle=False)
    tape = np.asarray(z["tape"])
    assert tape.dtype == np.int32 and tape.shape[1] == 13
    return [r for r in tape if int(r[_C_OID]) >= 1]


def _fixture_sessions() -> Dict[str, List[np.ndarray]]:
    """One session per (fixture, contract). A multi-contract fixture is split
    per contract (each contract has its own book)."""
    out: Dict[str, List[np.ndarray]] = {}
    for name in ALL_FIXTURES:
        rows = _fixture_rows(name)
        cids = sorted({int(r[_C_CID]) for r in rows})
        stem = name[:-4]
        if len(cids) == 1:
            out[stem] = rows
        else:
            for c in cids:
                out[f"{stem}#c{c}"] = [r for r in rows if int(r[_C_CID]) == c]
    return out


