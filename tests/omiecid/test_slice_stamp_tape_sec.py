Step = Union[np.ndarray, Callable]


def _new_book(cid: int = CONTRACT_ID) -> ContractBook:
    contract = Contract(contract_id=cid, delivery_start_minutes=_DELIVERY_START,
                        delivery_end_minutes=_DELIVERY_END, gct_minutes=_GCT,
                        status=ContractStatus.OPEN)
    return ContractBook(contract, _PC, _MC)


class Run:
    """Replay a script on a fresh ``book.init()`` through ``submit_order``.

    ``rows[i]`` is the row actually submitted at step i; ``pre_states[i]`` /
    ``states[i]`` / ``results[i]`` the state before / after it and its
    SubmitResult. ``require_accept`` asserts every row is accepted (synthetic
    scripts); fixture replays record rejections without failing.
    """

    def __init__(self, script: Sequence[Step], require_accept: bool = True):
        rows0 = [s for s in script if isinstance(s, np.ndarray)]
        cid = int(rows0[0][_C_CID]) if rows0 else CONTRACT_ID
        self.book = _new_book(cid)
        state = self.book.init()
        self.rows, self.pre_states, self.states, self.results = [], [], [], []
        for step in script:
            row = step(state) if callable(step) else step
            self.pre_states.append(state)
            state, res = self.book.submit_order(
                state, _row_to_order_traced(jnp.asarray(row), _PC))
            if require_accept:
                assert bool(res.accepted), f"row {row.tolist()} rejected"
            self.rows.append(row)
            self.states.append(state)
            self.results.append(res)

    @property
    def final(self):
        return self.states[-1]


