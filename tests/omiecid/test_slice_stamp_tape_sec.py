def _entry_events(run: Run) -> List[Dict[Tuple[int, int], Optional[Tuple[int, int]]]]:
    """For every state, map each live row (side, OID) to its queue EVENT:

    * ``(i, 0)`` — the row is the step-i aggressor's own entry (its resting
      remainder, its first slice): arrival at step i.
    * ``(i, 1)`` — an iceberg slice activated in step i's matching process
      (the OID traded at least its whole pre-step visible quantity in step i
      and still shows a row).
    * inherited — the row was live before step i, did not trade in step i (or
      traded only part of its visible quantity) and kept its stamp.
    * ``None`` — any other new or restamped row (an eviction heal: an
      engineering-limit stamp, card "Intentionally not done"); excluded from
      the ordering check.

    Requires an unsaturated trade tape (trades are attributed per step).
    """
    events: List[Dict] = []
    prev: Dict[Tuple[int, int], Optional[Tuple[int, int]]] = {}
    for i, row in enumerate(run.rows):
        pre, st = run.pre_states[i], run.states[i]
        assert not _tape_saturated(st), "processing-order check needs an unsaturated tape"
        traded: Dict[int, int] = {}
        for (_p, q, pas, _agr) in _new_trades(run, i):
            traded[pas] = traded.get(pas, 0) + q
        agg = int(row[_C_OID])
        cur: Dict[Tuple[int, int], Optional[Tuple[int, int]]] = {}
        for side in (BUY, SELL):
            for r in _live(st, side):
                oid = int(r[_OID])
                k = (side, oid)
                if oid == agg and side == int(row[_C_SIDE]):
                    cur[k] = (i, 0)
                    continue
                pre_rows = _live(pre, side)
                pre_r = pre_rows[pre_rows[:, _OID] == oid]
                if oid in traded:
                    vis = int(pre_r[0][_Q]) if len(pre_r) else 0
                    if traded[oid] >= vis:
                        cur[k] = (i, 1)
                    else:
                        cur[k] = prev.get(k)
                    continue
                if (len(pre_r) == 1 and int(pre_r[0][_SEC]) == int(r[_SEC])
                        and int(pre_r[0][_NSEC]) == int(r[_NSEC])):
                    cur[k] = prev.get(k)
                else:
                    cur[k] = None
        events.append(cur)
        prev = cur
    return events


def _processing_order_violations(run: Run) -> List[str]:
    """Pairs of live rows whose stored ``(SEC, NSEC)`` contradicts processing
    order: a row whose event comes from an earlier step must store a smaller
    key than a row from a later step; within one step the aggressor's own
    entry ``(i, 0)`` precedes every slice its process activated ``(i, 1)``.
    The order among slices of one step is not checked here ((5) pins it)."""
    out = []
    for i, (st, ev) in enumerate(zip(run.states, _entry_events(run))):
        keyed = []
        for side in (BUY, SELL):
            for r in _live(st, side):
                e = ev.get((side, int(r[_OID])))
                if e is not None:
                    keyed.append((e, (int(r[_SEC]), int(r[_NSEC])), side, int(r[_OID])))
        for a in keyed:
            for b in keyed:
                if a[0] < b[0] and not a[1] < b[1]:
                    out.append(f"step {i}: {a[2:]} event {a[0]} key {a[1]} "
                               f"!< {b[2:]} event {b[0]} key {b[1]}")
    return out


def _s5_a2_violations(run: Run) -> List[str]:
    out = []
    for i, st in enumerate(run.states):
        c = int(st.ts_counter)
        for sec, nsec, side, oid in _all_live_keys(st):
            if not sec < c:
                out.append(f"step {i}: side {side} oid {oid} SEC {sec} >= ts_counter {c}")
    return out


def _is_tape_only(rows: Sequence[np.ndarray]) -> bool:
    """Tape-only and time-ordered: seconds never decrease."""
    ts = [int(r[_C_TS]) for r in rows]
    return all(a <= b for a, b in zip(ts, ts[1:]))


