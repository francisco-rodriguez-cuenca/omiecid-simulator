# Trajectory digests for (7) / (8)
# ---------------------------------------------------------------------------
def _upd(m, *arrs) -> None:
    for a in arrs:
        a = np.ascontiguousarray(np.asarray(a))
        m.update(str((a.dtype.str, a.shape)).encode())
        m.update(a.tobytes())


_FIELDS = ("tape", "result", "ts_counter", "iceberg_meta", "book_pqot",
           "sec_all", "sec_non_ice", "nsec_all")


def _trajectory_digests(run: Run, ice: set) -> Dict[str, str]:
    """sha256[:16] per compared field, accumulated over EVERY submit of the
    session (so equality means equality after every submit).

    * tape: ``lob.trades``; result: the five SubmitResult fields;
      ts_counter; iceberg_meta: ``iceberg_meta`` + ``n_active``.
    * book_pqot: the P, Q, OID and TID columns of every row of both sides.
    * sec_all: the SEC column of every row; sec_non_ice: the SEC column with
      the cells of rows whose OID is an iceberg OID of the session masked.
    * nsec_all: the NSEC column of every row (never compared for equality;
      used by the (7) non-null only).
    """
    ms = {f: hashlib.sha256() for f in _FIELDS}
    for st, res in zip(run.states, run.results):
        _upd(ms["tape"], st.lob.trades)
        _upd(ms["result"],
             np.asarray(res.accepted, np.bool_), np.asarray(res.traded, np.bool_),
             np.asarray(res.trade_qty, np.float32),
             np.asarray(res.trade_price, np.float32),
             np.asarray(res.settlement_value, np.float32))
        _upd(ms["ts_counter"], np.asarray(st.ts_counter, np.int32))
        _upd(ms["iceberg_meta"], st.iceberg_meta, np.asarray(st.n_active, np.int32))
        for side in (BUY, SELL):
            a = _side_arr(st, side)
            _upd(ms["book_pqot"], a[:, [_P, _Q, _OID, _TID]])
            _upd(ms["sec_all"], a[:, _SEC])
            sec = a[:, _SEC].copy()
            sec[np.isin(a[:, _OID], np.asarray(sorted(ice), dtype=a.dtype))] = -7
            _upd(ms["sec_non_ice"], sec)
            _upd(ms["nsec_all"], a[:, _NSEC])
    return {f: m.hexdigest()[:16] for f, m in ms.items()}


def _final_ice_sec_cells(run: Run, ice: set) -> Tuple[Tuple[int, int, int], ...]:
    """(side, OID, SEC) of every live iceberg-OID row of the final book."""
    out = []
    for side in (BUY, SELL):
        for r in _live(run.final, side):
            if int(r[_OID]) in ice:
                out.append((side, int(r[_OID]), int(r[_SEC])))
    return tuple(sorted(out))


