def _full_own_side_same_price(side: int) -> Tuple[List[np.ndarray], int, int, float, int]:
    """Incoming-ICE heal (default book_depth = 100, no extra compile).

    The own side is filled to 100 rows, ALL at one price ``p``: iceberg X
    (oid 9001, 3.0/0.4, t1) plus 99 NONs. A non-crossing incoming ICE Y
    (oid 5555, 2.0/0.5, t30) at the same price ``p``: its sweep pass rests on
    the full side, so jaxob wipes the whole worst level ``p`` (X's slice and
    the 99 NONs, an engineering-limit loss); the IOC post cancels the pass
    remainder, Y's first slice rests at (30, .), and the heal regen re-shows
    X's evicted slice at ``p``. Returns (script, X, Y, p_eur, entry_second).
    """
    p = 40.07 if side == BUY else 60.03
    rows = [_row(side, p, 3.0, 9001, 1, ICE, 0.4)]
    rows += [_row(side, p, 0.3, 20000 + i, 2 + i // 10) for i in range(99)]
    rows += [_row(side, p, 2.0, 5555, 30, ICE, 0.5)]
    return rows, 9001, 5555, p, 30


def _sweep_plus_heal(side: int = BUY) -> Tuple[List[np.ndarray], Dict[str, int]]:
    """One incoming-ICE submit with a sweep regen AND a heal regen.

    Own side (BUY here): iceberg X (oid 9001, 3.0/0.4) alone at the worst
    price 40.01, 99 NONs at distinct better prices 40.02..41.00. Opposite:
    SELL ICEwPI R (oid 777, 4.0/1.0 @ 41.50, PPD +0.40). Incoming BUY ICE Y
    (oid 61, 3.0/1.0 @ 41.60, t200): pass 1 trades R's slice 1 @ 41.50 and its
    remainder rests on the full side (X's level wiped); the fill path
    regenerates R (slice 2 drifts to 41.90, beyond 41.60) and X. Pass 2 does
    not cross and rests on the full side again (X wiped again); the IOC post
    cancels it; Y's first slice rests; the heal regen re-shows X (wiping the
    worst NON level 40.02)."""
    assert side == BUY
    rows = [_row(BUY, 40.01, 3.0, 9001, 1, ICE, 0.4)]
    rows += [_row(BUY, round(40.02 + 0.01 * i, 2), 0.3, 30000 + i, 2 + i)
             for i in range(99)]
    rows += [_row(SELL, 41.50, 4.0, 777, 150, ICE, 1.0, 0.40),
             _row(BUY, 41.60, 3.0, 61, 200, ICE, 1.0)]
    return rows, {"x": 9001, "r": 777, "y": 61, "e": 200}


